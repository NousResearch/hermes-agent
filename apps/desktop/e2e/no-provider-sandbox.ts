/**
 * What keeps a sandbox without a provider off the network.
 *
 * A sandbox without a provider is a fresh desktop install, and a fresh install's first-run
 * onboarding claims the Nous welcome trial: `onboarding.start` mints a guest account at the Nous
 * portal, exchanges it for an inference token (which can put a browser check from the portal on
 * screen) and opens the setup chat on the free model. A test must never do that from a developer's
 * machine, so the sandbox switches guests off (`nous.guest: false`, the gate every guest creator
 * checks before it touches the portal). With no trial and no provider, a first boot lands on
 * provider setup. The Nous URL overrides point at a closed loopback port as a second wall, and the
 * proxy variables send every proxy-aware client to a local recorder (`egress-recorder.ts`) that
 * refuses it, so the catalog and update fetches a backend makes at boot stay on this machine too
 * and a spec can see what was attempted. Chromium does not read the proxy variables on macOS or
 * Windows (it follows the system settings), so the app itself gets the recorder as its
 * `--proxy-server`: the renderer's web font and the main process's fetches end there as well.
 */

import { parse } from 'yaml'

/**
 * config.yaml of a sandbox with no provider: guests off, and the UI in English, since the specs
 * find controls by their English names and the desktop otherwise follows the OS language.
 */
export const NO_PROVIDER_CONFIG =
  '# Auto-generated by E2E test fixtures — no providers configured\nnous:\n  guest: false\ndisplay:\n  language: en\n'

/** A loopback port nothing listens on: a Nous call that ignored the guest gate fails at once. */
const CLOSED_LOOPBACK = 'http://127.0.0.1:1'

/** The overrides the backend and the desktop read for the Nous portal and inference hosts. */
const NOUS_URL_KEYS = ['HERMES_PORTAL_BASE_URL', 'NOUS_PORTAL_BASE_URL', 'NOUS_INFERENCE_BASE_URL'] as const

/**
 * Every proxy variable in both spellings. Python's `urllib.request.getproxies` (which httpx uses)
 * lets the lowercase one win, so a developer's own `https_proxy` would beat an uppercase override.
 */
const PROXY_KEYS = ['HTTPS_PROXY', 'https_proxy', 'HTTP_PROXY', 'http_proxy', 'ALL_PROXY', 'all_proxy'] as const

const LOOPBACK_HOSTS = new Set(['localhost', '127.0.0.1', '::1', '[::1]'])

/** The sandbox env that keeps Nous traffic and proxy-aware clients on this machine. */
export function noProviderNetworkEnv(recorderUrl: string): Record<string, string> {
  const env: Record<string, string> = {
    HERMES_PORTAL_BASE_URL: CLOSED_LOOPBACK,
    NOUS_PORTAL_BASE_URL: CLOSED_LOOPBACK,
    NOUS_INFERENCE_BASE_URL: `${CLOSED_LOOPBACK}/v1`,
    NO_PROXY: 'localhost,127.0.0.1,::1',
    no_proxy: 'localhost,127.0.0.1,::1',
    // A partial-clone checkout turns some backend git reads into a lazy fetch (as coreAppEnv does).
    GIT_NO_LAZY_FETCH: '1'
  }

  for (const key of PROXY_KEYS) {
    env[key] = recorderUrl
  }

  return env
}

const PROXY_SWITCH = '--proxy-server='

/**
 * The launch switches that send the app's own requests (renderer and main process) to the
 * recorder. Chromium never proxies loopback, so the app still reaches its local backend.
 */
export function chromiumProxyArgs(recorderUrl: string): string[] {
  return [`${PROXY_SWITCH}${recorderUrl}`]
}

function isLoopbackHost(hostname: string): boolean {
  return LOOPBACK_HOSTS.has(hostname.toLowerCase()) || /^127(?:\.\d{1,3}){3}$/.test(hostname)
}

function isLoopbackUrl(raw: string): boolean {
  try {
    return isLoopbackHost(new URL(raw).hostname)
  } catch {
    return false
  }
}

/** Why a no-provider launch with `configYaml`, `env` and `args` could reach a host off this machine. */
export function offlineViolations(
  configYaml: string,
  env: Record<string, string | undefined>,
  args: readonly string[]
): string[] {
  const problems: string[] = []
  const config = (parse(configYaml) ?? {}) as { nous?: { guest?: unknown } }

  if (config.nous?.guest !== false) {
    problems.push('config.yaml does not set nous.guest: false')
  }

  for (const key of [...NOUS_URL_KEYS, ...PROXY_KEYS]) {
    const value = env[key]

    if (!value) {
      problems.push(`${key} is unset`)
    } else if (!isLoopbackUrl(value)) {
      problems.push(`${key}=${value} is not loopback`)
    }
  }

  const proxySwitch = args.find(arg => arg.startsWith(PROXY_SWITCH))

  if (!proxySwitch) {
    problems.push(`the app is launched without ${PROXY_SWITCH}<recorder>`)
  } else if (!isLoopbackUrl(proxySwitch.slice(PROXY_SWITCH.length))) {
    problems.push(`${proxySwitch} is not loopback`)
  }

  return problems
}

/**
 * The Nous account and inference hosts (`hermes_cli/auth_constants.py` DEFAULT_NOUS_PORTAL_URL,
 * DEFAULT_NOUS_INFERENCE_URL, DEFAULT_NOUS_WELCOME_URL): where a guest is minted, its token
 * exchanged, its browser check served and the free model run.
 */
const NOUS_ACCOUNT_HOSTS = new Set([
  'portal.nousresearch.com',
  'inference-api.nousresearch.com',
  'welcome-api.nousresearch.com'
])

/** The `host:port` attempts in `hosts` aimed at a Nous account or inference host. */
export function nousAccountAttempts(hosts: Iterable<string>): string[] {
  return [...hosts].filter(host => NOUS_ACCOUNT_HOSTS.has(host.replace(/:\d+$/, '').toLowerCase()))
}
