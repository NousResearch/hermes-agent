interface ArabicForms {
  one: string
  two: string
  few: string
  many: string
  other: string
}

const AR_RULES = new Intl.PluralRules('ar')
const AR_ITEMS: ArabicForms = { one: 'عنصر واحد', two: 'عنصران', few: 'عناصر', many: 'عنصرًا', other: 'عنصر' }
const AR_MESSAGES: ArabicForms = { one: 'رسالة واحدة', two: 'رسالتان', few: 'رسائل', many: 'رسالة', other: 'رسالة' }

/** Arabic counts: the singular and dual replace the number; the rest follow it. */
function arCount(n: number, forms: ArabicForms): string {
  const form = AR_RULES.select(n)

  return form === 'one' || form === 'two' ? forms[form] : `${n} ${forms[form === 'zero' ? 'other' : form]}`
}

