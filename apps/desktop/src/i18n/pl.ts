// PL_PLURAL: (count, one, few, many) — polskie formy liczby mnogiej
// 1 → one ("1 sesja"), 2-4 (poza 12-14) → few ("3 sesje"), reszta → many ("5 sesji")
const plNum = (count: number | string) => (typeof count === 'string' ? Number(count) || 0 : count)

const PL_PLURAL = (count: number | string, one: string, few: string, many: string) => {
  const c = plNum(count)
  const n = Math.abs(c) % 10
  const nn = Math.abs(c) % 100

  return Math.abs(c) === 1 ? one : n >= 2 && n <= 4 && (nn < 12 || nn > 14) ? few : many
}

