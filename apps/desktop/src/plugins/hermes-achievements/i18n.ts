export function useAchievementsI18n() {
  const t = usePluginI18n('hermes-achievements')

  return useMemo(
    () => ({
      nav: t('nav'),
      open: t('open'),
      title: t('title'),
      subtitle: t('subtitle'),
      unlockedSummary: (unlocked: number, total: number) => t('unlockedSummary', unlocked, total),
      discoveredSummary: (count: number) => t('discoveredSummary', count),
      secretSummary: (count: number) => t('secretSummary', count),
      search: t('search'),
      searchLabel: t('searchLabel'),
      stateFilter: t('stateFilter'),
      all: t('all'),
      unlocked: t('unlocked'),
      inProgress: t('inProgress'),
      secret: t('secret'),
      scan: t('scan'),
      scanning: t('scanning'),
      loadingTitle: t('loadingTitle'),
      loadingDescription: t('loadingDescription'),
      emptyTitle: t('emptyTitle'),
      emptyDescription: t('emptyDescription'),
      noMatchTitle: t('noMatchTitle'),
      noMatchDescription: t('noMatchDescription'),
      errorTitle: t('errorTitle'),
      retry: t('retry'),
      stale: t('stale'),
      scanFailed: t('scanFailed'),
      scanPending: t('scanPending'),
      scanRunning: t('scanRunning'),
      scanProgress: (current: number, total: number) => t('scanProgress', current, total),
      scanProgressUnknown: t('scanProgressUnknown'),
      unlockedBadge: t('unlockedBadge'),
      nextTier: (tier: string) => t('nextTier', tier),
      complete: t('complete'),
      hidden: t('hidden'),
      progressValue: (progress: number, threshold: number) => t('progressValue', progress, threshold),
      unlockedOn: (date: string) => t('unlockedOn', date),
      evidence: (title: string) => t('evidence', title),
      unknownError: t('unknownError')
    }),
    [t]
  )
}
