const plural = (n: number, one: string, other: string) => n === 1 ? one : other

/** Russian: one / few / many by the last two digits. */
function ru(n: number, one: string, few: string, many: string) {
  const tens = n % 100, unit = n % 10

  return unit === 1 && tens !== 11 ? one : unit >= 2 && unit <= 4 && (tens < 12 || tens > 14) ? few : many
}

/** Arabic: the number is part of the dual and singular forms. */
function ar(n: number, forms: { one: string; two: string; few: string; many: string }) {
  const tens = n % 100

  return n === 1 ? forms.one : n === 2 ? forms.two : tens >= 3 && tens <= 10 ? forms.few.replace('#', String(n)) : forms.many.replace('#', String(n))
}

