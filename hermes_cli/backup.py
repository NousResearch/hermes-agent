# Shared full-zip backup helper
# ---------------------------------------------------------------------------

def _write_full_zip_backup(
    out_path: Path,
    hermes_root: Path,
    credential_layout: Optional[
        tuple[Path, Path, bool, list[_BackupCredential]]
    ] = None,
) -> Optional[Path]:
    """Write a full zip snapshot of ``hermes_root`` to ``out_path``.

    Uses the same exclusion rules and SQLite safe-copy as :func:`run_backup`.
    Returns the output path on success, None on failure (nothing to back up,
    or write error — caller should surface the outcome but not raise).
    """
    files_to_add: list[tuple[Path, Path]] = []
    try:
        if credential_layout is None:
            credential_layout = _collect_residence_backup_files(
                hermes_root,
                ambient_active_home=False,
            )
        auth_root, shared_store_path, distinct_residence, auth_to_add = (
            credential_layout
        )
    except (OSError, RuntimeError, ValueError) as exc:
        logger.warning("Full-zip backup: credential inspection failed: %s", exc)
        return None
    try:
        for dirpath, dirnames, filenames in os.walk(hermes_root, followlinks=False):
            dp = Path(dirpath)
            # Prune excluded directories in-place so os.walk doesn't descend
            rel_dir = dp.relative_to(hermes_root)
            dirnames[:] = [
                d
                for d in dirnames
                if d not in _EXCLUDED_DIRS
                and not (rel_dir == Path(".") and d == _AUTH_RESIDENCE_DIR)
            ]

            for fname in filenames:
                fpath = dp / fname
                try:
                    rel = fpath.relative_to(hermes_root)
                except ValueError:
                    continue

                if _should_skip_backup_file(fpath, rel, out_path):
                    continue
                if _skip_runtime_auth_member(
                    fpath,
                    rel,
                    auth_root,
                    shared_store_path,
                    distinct_residence,
                ):
                    continue

                files_to_add.append((fpath, rel))
    except OSError as exc:
        logger.warning("Full-zip backup: walk failed: %s", exc)
        return None

    if not files_to_add and not auth_to_add:
        return None

    backup_failed = False
    try:
        with zipfile.ZipFile(out_path, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as zf:
            for abs_path, rel_path in files_to_add:
                try:
                    if abs_path.suffix == ".db":
                        # Stage the snapshot alongside the output zip so that the
                        # temp file lives on the same filesystem.  The system
                        # default (/tmp) may be a small tmpfs that cannot hold
                        # large databases, causing silent backup incompleteness.
                        with tempfile.NamedTemporaryFile(
                            suffix=".db", delete=False, dir=str(out_path.parent)
                        ) as tmp:
                            tmp_db = Path(tmp.name)
                        try:
                            if not _safe_copy_db(abs_path, tmp_db):
                                logger.warning(
                                    "Full-zip backup aborted: SQLite snapshot failed for %s",
                                    rel_path,
                                )
                                backup_failed = True
                                break
                            zf.write(tmp_db, arcname=str(rel_path))
                        finally:
                            tmp_db.unlink(missing_ok=True)
                    else:
                        zf.write(abs_path, arcname=str(rel_path))
                except (PermissionError, OSError, ValueError) as exc:
                    logger.debug("Skipping %s in zip backup: %s", rel_path, exc)
                    continue
            if not backup_failed:
                for credential in auth_to_add:
                    try:
                        payload = _read_backup_credential(credential)
                        zf.writestr(
                            credential.archive_path.as_posix(),
                            payload,
                        )
                    except (
                        PermissionError,
                        OSError,
                        RuntimeError,
                        ValueError,
                    ) as exc:
                        logger.warning(
                            "Full-zip backup aborted: credential capture "
                            "failed for %s: %s",
                            credential.archive_path,
                            exc,
                        )
                        backup_failed = True
                        break
    except OSError as exc:
        logger.warning("Full-zip backup: zip write failed: %s", exc)
        # Best-effort cleanup of partial file
        try:
            out_path.unlink(missing_ok=True)
        except OSError:
            pass
        return None

    if backup_failed:
        try:
            out_path.unlink(missing_ok=True)
        except OSError:
            pass
        return None

    return out_path


