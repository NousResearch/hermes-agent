"""``hermes gateway migrate --backends``: a READ-ONLY report of the serve/dashboard background
services on this machine and what a future backend migration would do to each.

Hermes never installs a ``hermes serve`` / ``hermes dashboard`` service itself, so every one found
here was set up by someone else: a systemd unit copied from the docs, a hand-written launchd plist,
the Nix ``hermes-backend`` unit (NixOS and Home Manager), the Docker image's s6 ``dashboard``
longrun or the Compose ``dashboard`` sidecar, a Desktop SSH ``serve`` backend, or a process started
by hand. The report says which supervisor owns each backend, by what the process runs and which
unit's ``MainPID`` it is, never by unit name (Nix calls it ``hermes-backend``).

Nothing here stops, restarts, edits or writes anything, and nothing touches the network: only
``ps``, ``/proc`` reads, plist reads and ``systemctl show`` / ``list-unit-files`` / ``launchctl
print`` queries. The spawn ledger is deliberately not read, because reading a corrupt ledger
quarantines (renames) it.
"""

from __future__ import annotations

import contextlib
import json
import os
import shlex
import subprocess
import sys
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Optional

# Unit-name patterns for installed-but-not-running units. Running backends are found by argv, so a
# unit with any other name is still reported while it runs.
_UNIT_PATTERNS = ("hermes-serve*", "hermes-dashboard*", "hermes-backend*")
_ENABLED_STATES = frozenset({"enabled", "enabled-runtime", "linked", "linked-runtime", "static",
                             "generated", "alias", "indirect"})
_CONTAINER_CGROUP_MARKERS = ("docker", "containerd", "libpod", "kubepods", "/lxc/")
_NOT_APPLIED = "Report only: --backends never changes anything; applying a backend migration is not implemented yet."

# supervisor -> (what a future migration would do, why it cannot simply be done for you)
_PLANS: dict[str, tuple[str, str]] = {
    "systemd": (
        "Stop and disable this unit once the host gateway serves the dashboard, keeping the unit file for review.",
        "The unit was written by hand (Hermes never installs one); its flags and environment are yours."),
    "nix-systemd": (
        "Set services.hermes-agent.backend.mode = \"none\" in your Nix configuration and rebuild.",
        "The unit file is generated by Nix and read-only; the change belongs in your Nix configuration."),
    "launchd": (
        "Boot out this launchd job and move its plist aside once the host gateway serves the dashboard.",
        "The plist was written by hand (Hermes never installs one); KeepAlive would undo a plain stop."),
    "nix-launchd": (
        "Set backend.mode = \"none\" in your Home Manager / nix-darwin configuration and switch.",
        "The plist is generated by Nix and read-only; the change belongs in your Nix configuration."),
    "s6": (
        "Leave HERMES_DASHBOARD unset for this container so the s6 dashboard slot stays down.",
        "The slot is declared by the container image; the switch is the container's environment."),
    "container": (
        "Remove the dashboard service (e.g. the Compose `dashboard` sidecar) from your container setup.",
        "The process belongs to a container; its definition lives in your Compose file or run command."),
    "desktop-ssh": (
        "Nothing: Hermes Desktop starts and stops this SSH backend itself.",
        "It is owned by a Desktop SSH session; stopping it would disconnect that client."),
    "desktop-local": (
        "Nothing: Hermes Desktop starts and stops its local backend itself.",
        "It is owned by the Desktop app."),
    "detached": (
        "Stop this process once the host gateway serves the dashboard; nothing restarts it.",
        "No supervisor owns it, so whoever started it may still rely on its host/port."),
    "manual": (
        "Stop this process once the host gateway serves the dashboard.",
        "It was started from a shell or another program that may still be using it."),
    "unknown": (
        "Find what starts this backend (on Windows: a Scheduled Task or Startup-folder entry) and remove it.",
        "Its supervisor could not be identified, so there is nothing safe to change automatically."),
}


@dataclass
class BackendItem:
    supervisor: str
    running: bool
    pid: Optional[int] = None
    argv: list[str] = field(default_factory=list)
    unit: Optional[str] = None  # systemd unit / launchd label / s6 slot
    scope: Optional[str] = None  # systemd "user"/"system", launchd domain
    unit_path: Optional[str] = None  # unit file / plist / s6 service dir
    state: Optional[str] = None  # systemd UnitFileState
    hermes_home: Optional[str] = None
    this_home: Optional[bool] = None
    would: str = ""
    not_applied: str = ""
    notes: list[str] = field(default_factory=list)


# --------------------------------------------------------------------------- read-only probes


def _systemctl_query(scope: Optional[str], *args: str) -> Optional[str]:
    """stdout of a read-only ``systemctl [--user] <args>``; None when unavailable or non-zero."""
    from hermes_cli.main_dashboard import _SYSTEMCTL_ERRORS, _run_probe
    cmd = ["systemctl", *(["--user"] if scope == "user" else []), *args]
    try:
        result = _run_probe(cmd, timeout=10)
    except _SYSTEMCTL_ERRORS:
        return None
    return result.stdout or "" if result.returncode == 0 else None


def _unit_properties(unit: str, scope: Optional[str]) -> dict[str, str]:
    """``FragmentPath`` / ``UnitFileState`` / ``ActiveState`` / ``Environment`` of *unit*."""
    for candidate in ([scope] if scope else ["user", "system"]):
        out = _systemctl_query(candidate, "show", unit, "--no-pager", "--property=FragmentPath",
                               "--property=UnitFileState", "--property=ActiveState", "--property=Environment")
        if out is None:
            continue
        props = dict(line.split("=", 1) for line in out.splitlines() if "=" in line)
        if props.get("FragmentPath"):
            props["Scope"] = candidate
            return props
    return {}


def _env_home(environment: str) -> Optional[str]:
    """``HERMES_HOME`` from a ``systemctl show -p Environment`` value, or None."""
    try:
        tokens = shlex.split(environment)
    except ValueError:
        tokens = environment.split()
    return next((t.split("=", 1)[1] for t in tokens if t.startswith("HERMES_HOME=")), None)


def _nix_managed(path: Optional[str]) -> bool:
    """True when *path* is (or links into) the read-only Nix store."""
    if not path:
        return False
    if path.startswith("/nix/store/"):
        return True
    with contextlib.suppress(OSError, RuntimeError):
        return str(Path(path).resolve()).startswith("/nix/store/")
    return False


def _installed_units() -> list[tuple[str, str, str]]:
    """``(unit, scope, unit_file_state)`` for every hermes-serve*/-dashboard*/-backend* unit file."""
    found: list[tuple[str, str, str]] = []
    for scope in ("user", "system"):
        out = _systemctl_query(scope, "list-unit-files", "--no-legend", "--no-pager", "--plain", *_UNIT_PATTERNS)
        for line in (out or "").splitlines():
            parts = line.split()
            if len(parts) >= 2 and parts[0].endswith(".service"):
                found.append((parts[0], scope, parts[1]))
    return found


def _launchd_plist_paths() -> dict[str, str]:
    """``label -> plist path`` across the launchd plist dirs (read-only)."""
    import plistlib
    from xml.parsers.expat import ExpatError

    from hermes_cli.main_dashboard import _launchd_plist_dirs
    paths: dict[str, str] = {}
    for _kind, plist_dir in _launchd_plist_dirs():
        try:
            plists = sorted(plist_dir.glob("*.plist"))
        except OSError:
            continue
        for plist_path in plists:
            try:
                with open(plist_path, "rb") as f:
                    data = plistlib.load(f)
            except (OSError, ValueError, plistlib.InvalidFileException, ExpatError):
                continue
            if isinstance(data, dict) and (label := str(data.get("Label") or "").strip()):
                paths.setdefault(label, str(plist_path))
    return paths


def _s6_slot(pid: int) -> Optional[tuple[str, str]]:
    """``(slot, service_dir)`` when an ancestor of *pid* is ``s6-supervise <dir>``."""
    from hermes_cli.dashboard_procs import _process_ancestors
    from hermes_cli.main_dashboard import _dashboard_cmdline_for_pid
    for ancestor in _process_ancestors(pid):
        argv = _dashboard_cmdline_for_pid(ancestor) or []
        if argv and os.path.basename(argv[0]) == "s6-supervise":
            service_dir = argv[1] if len(argv) > 1 else ""
            return os.path.basename(service_dir.rstrip("/")) or "?", service_dir
    return None


def _container_cgroup(pid: int) -> bool:
    from hermes_cli.main_dashboard import _pid_unified_cgroup_entries
    return any(m in entry for entry in _pid_unified_cgroup_entries(pid) for m in _CONTAINER_CGROUP_MARKERS)


def _in_container() -> bool:
    from hermes_cli._startup_fast import is_container_startup_environment
    return is_container_startup_environment()


# --------------------------------------------------------------------------- classification


def _running_backends() -> list[tuple[int, str]]:
    """``(pid, command)`` of every live serve/dashboard (argv scan only, never the spawn ledger)."""
    from hermes_cli.dashboard_procs import _iter_process_table
    from hermes_cli.update_cmd_windows import _hermes_holder_subcommand
    try:
        rows = _iter_process_table()
    except (FileNotFoundError, subprocess.TimeoutExpired, OSError):  # same failures the update sweep tolerates
        return []
    me = os.getpid()
    return [(pid, cmd) for pid, cmd in rows if pid != me and _hermes_holder_subcommand(cmd) in ("serve", "dashboard")]


def _classify_running(pid: int, command: str, *, launchd_jobs, plist_paths, ssh_pids, desktop_pids,
                      seen_units: set[str]) -> BackendItem:
    from hermes_cli._startup_fast import is_desktop_ssh_backend_argv
    from hermes_cli.dashboard_procs import _is_desktop_local_serve_cmdline, _process_ancestors, _process_ppid
    from hermes_cli.main_dashboard import (
        _dashboard_cmdline_for_pid,
        _launchd_job_owning_backend,
        _systemd_owner_for_pid,
    )
    argv = _dashboard_cmdline_for_pid(pid)
    if not argv:
        try:
            argv = shlex.split(command)
        except ValueError:
            argv = command.split()
    item = BackendItem(supervisor="unknown", running=True, pid=pid, argv=list(argv))
    if owner := _systemd_owner_for_pid(pid):
        unit, scope = owner
        props = _unit_properties(unit, scope)
        seen_units.add(f"{props.get('Scope', scope)}:{unit}")
        item.unit, item.scope = unit, props.get("Scope", scope)
        item.unit_path, item.state = props.get("FragmentPath") or None, props.get("UnitFileState") or None
        item.supervisor = "nix-systemd" if _nix_managed(item.unit_path) else "systemd"
    elif slot := _s6_slot(pid):
        item.supervisor, item.unit = "s6", slot[0]
        item.unit_path = slot[1] if os.path.isabs(slot[1]) else None  # s6-supervise runs from the scandir
        if _container_cgroup(pid):
            item.notes.append("Runs inside a container (seen from the host).")
    elif launchd_jobs and (job := _launchd_job_owning_backend(pid, argv, launchd_jobs,
                                                                ancestors=_process_ancestors(pid))):
        domain, label, _live = job
        item.unit, item.scope, item.unit_path = label, domain, plist_paths.get(label)
        item.supervisor = "nix-launchd" if _nix_managed(item.unit_path) else "launchd"
    elif pid in ssh_pids or is_desktop_ssh_backend_argv(argv):
        item.supervisor = "desktop-ssh"
    elif pid in desktop_pids or _is_desktop_local_serve_cmdline(command):
        item.supervisor = "desktop-local"
    elif _container_cgroup(pid) or _in_container():
        item.supervisor = "container"
    elif sys.platform != "win32":
        ppid = _process_ppid(pid)
        item.supervisor = "unknown" if ppid is None else ("detached" if ppid <= 1 else "manual")
    with contextlib.suppress(Exception):
        from hermes_cli.dashboard_procs import _hermes_home_for_pid
        item.hermes_home = _hermes_home_for_pid(pid)
    return item


def _finish(item: BackendItem, own_home: str) -> BackendItem:
    from hermes_cli.dashboard_procs import _normalized_home_for_compare
    from hermes_cli.update_cmd_fleet import _is_serve_or_dashboard_unit
    item.would, why = _PLANS[item.supervisor]
    item.not_applied = f"{_NOT_APPLIED} {why}"
    if item.hermes_home:
        item.this_home = _normalized_home_for_compare(item.hermes_home) == _normalized_home_for_compare(own_home)
    if item.supervisor in ("systemd", "nix-systemd") and item.unit and not _is_serve_or_dashboard_unit(item.unit):
        item.notes.append("`hermes update`'s systemd unit pass matches only hermes-gateway*/hermes-serve*/"
                          f"hermes-dashboard* names, so it does not list {item.unit}.")
    if item.state == "disabled":
        item.notes.append("The unit is disabled: it does not start at boot.")
    return item


def collect_backends() -> list[BackendItem]:
    """Every serve/dashboard backend on this machine (running, or installed and enabled). Read-only."""
    from hermes_cli.dashboard_procs import _exclude_pids_from_env, _lock_owned_serve_pids
    from hermes_cli.main_dashboard import _loaded_launchd_backend_jobs
    from hermes_constants import get_hermes_home
    own_home = str(get_hermes_home())
    launchd_jobs = _loaded_launchd_backend_jobs()  # empty off macOS
    plist_paths = _launchd_plist_paths() if launchd_jobs else {}
    seen_units: set[str] = set()
    items = [_classify_running(pid, cmd, launchd_jobs=launchd_jobs, plist_paths=plist_paths,
                               ssh_pids=_lock_owned_serve_pids(), desktop_pids=_exclude_pids_from_env(),
                               seen_units=seen_units)
             for pid, cmd in _running_backends()]
    running_labels = {i.unit for i in items if i.supervisor in ("launchd", "nix-launchd")}
    for unit, scope, state in _installed_units():
        if f"{scope}:{unit}" in seen_units or state not in _ENABLED_STATES:
            continue
        props = _unit_properties(unit, scope)
        path = props.get("FragmentPath") or None
        items.append(BackendItem(supervisor="nix-systemd" if _nix_managed(path) else "systemd", running=False,
                                 unit=unit, scope=scope, unit_path=path, state=state,
                                 hermes_home=_env_home(props.get("Environment", ""))))
    for domain, label, argv, _live_pid in launchd_jobs:
        if label in running_labels:
            continue
        path = plist_paths.get(label)
        items.append(BackendItem(supervisor="nix-launchd" if _nix_managed(path) else "launchd", running=False,
                                 argv=list(argv), unit=label, scope=domain, unit_path=path))
    return [_finish(item, own_home) for item in items]


# --------------------------------------------------------------------------- output


def format_report(items: list[BackendItem]) -> list[str]:
    lines = ["Serve/dashboard background services (report only; nothing was changed)", ""]
    if not items:
        return lines + ["  No running or enabled hermes serve / hermes dashboard backend found."]
    for item in items:
        head = f"PID {item.pid}" if item.pid else "not running"
        where = f" {item.unit}" if item.unit else ""
        scope = f" ({item.scope})" if item.scope else ""
        lines.append(f"• {item.supervisor}{where}{scope}: {head}")
        if item.argv:
            lines.append(f"    runs:    {shlex.join(item.argv)}")
        if item.unit_path:
            lines.append(f"    file:    {item.unit_path}")
        if item.state:
            lines.append(f"    state:   {item.state}")
        if item.hermes_home:
            mine = " (this HERMES_HOME)" if item.this_home else ""
            lines.append(f"    home:    {item.hermes_home}{mine}")
        lines.append(f"    would:   {item.would}")
        lines.append(f"    not yet: {item.not_applied}")
        lines.extend(f"    note:    {n}" for n in item.notes)
    return lines


def cmd_backends_report(args) -> None:
    """``hermes gateway migrate --backends [--dry-run] [--json]``. Always exits 0 on valid arguments."""
    if getattr(args, "yes", False) or getattr(args, "multiplex", False):
        print("✗ --backends is a read-only report; it cannot be combined with --yes or --multiplex.",
              file=sys.stderr)
        sys.exit(2)
    items = collect_backends()
    if getattr(args, "json", False):
        print(json.dumps({"applied": False, "backends": [asdict(i) for i in items]}, indent=2))
        return
    print("\n".join(format_report(items)))
