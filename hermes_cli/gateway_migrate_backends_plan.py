_NEVER_TOUCHED = frozenset({"desktop-ssh", "desktop-local"})
_AUTH_PREFIX = "HERMES_DASHBOARD_"
_SECRET_KEY = "HERMES_DASHBOARD_BASIC_AUTH_SECRET"

