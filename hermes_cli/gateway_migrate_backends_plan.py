"""Plan + preflight for ``hermes gateway migrate --backends --apply --dry-run``: which old backend would
move, to which address, what would be copied, and every reason it cannot happen. Changes nothing.

The old backend (``hermes dashboard`` / ``hermes serve``) is found by the report's own detection
(:func:`hermes_cli.gateway_migrate_backends.collect_backends`); the target address is checked by the
gateway's own ``webapp.host`` validation (``gateway.webapp_listener``), so a specific-IP bind starts
working the day the gateway accepts one, without a change here.
"""

from __future__ import annotations

import ipaddress
import os
import re
import shlex
from dataclasses import dataclass, field
from typing import Optional

from hermes_cli.gateway_migrate_backends import BackendItem

