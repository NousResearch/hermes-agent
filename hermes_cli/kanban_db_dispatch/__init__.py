"""Dispatcher for the kanban board: crash/stale/orphan detection, failure accounting,
the respawn circuit breaker, memory-aware caps, the one-shot ``dispatch_once`` pass,
worker spawning, and the long-lived ``run_daemon`` loop.

Siblings: ``result`` (the dispatch result record), ``liveness`` (worker process
identity, exit classification, pid checks, termination primitives), ``reaper``
(terminal-worker reaping, heartbeat, max-runtime), ``stale`` (stale-claim and orphan
reconciliation), ``crash_sweep`` (dead-worker classification, failure accounting,
protocol-violation streak), ``respawn_guard`` (the circuit breaker and profile
allowlist), ``concurrency`` (memory-aware caps and running counts), ``tick`` (the
dispatch tick), ``spawn`` (argv/env resolution and ``_default_spawn``), ``daemon``
(the loop). ``_kb`` / ``_kbc`` / ``_kbda`` / ``_kbw`` are the late-bound accessors the
siblings reach the origin module through.

Split out of ``hermes_cli.kanban_db``; origin-resident helpers stay late-bound so
monkeypatching ``kanban_db.<name>`` keeps working.
"""

