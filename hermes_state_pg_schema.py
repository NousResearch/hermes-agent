def plan_postgres_migrations(
    current_version: int,
    applied: Optional[set] = None,
) -> List[PostgresMigration]:
    """Return pending Postgres-only migrations.

    *current_version* is the high-water mark from ``pg_migration_version``
    ``MAX(version)`` — NOT the shared ``SCHEMA_VERSION`` constant, which
    governs only the SQLite/shared schema.

    *applied* is the full set of recorded versions. It matters because an
    ``optional=True`` migration that fails does NOT record its version, while
    later migrations still succeed and do. A pure ``> MAX(version)`` rule would
    then strand the skipped one forever: pg_trgm denied by a managed provider's
    extension allow-list would never be retried even after an operator
    allow-lists it, because v19+ already pushed the high-water mark past it.

    Passing *applied* replays any gap below the high-water mark. Recorded
    migrations are skipped. Pending migrations must tolerate replay after a
    partial failure: conditional DDL and replaceable trigger definitions do,
    while projection repairs may invalidate cached fields again. Retrying a
    still-failing optional migration logs a warning on each connection.
    """
    if applied is None:
        return [m for m in _PG_ONLY_MIGRATIONS if m.version > current_version]
    return [
        m
        for m in _PG_ONLY_MIGRATIONS
        if m.version > current_version or m.version not in applied
    ]


def _probe_pg_trgm(conn: Any) -> bool:
    """Return ``True`` if pg_trgm is installed in the current database.

    TEST UTILITY — not called from the production path. Uses a catalog probe
    rather than ``try/except`` on DDL to avoid putting the psycopg connection
    into an aborted-transaction state.
    """
    try:
        row = conn.execute(
            "SELECT 1 FROM pg_catalog.pg_extension WHERE extname = 'pg_trgm'"
        ).fetchone()
        return row is not None
    except Exception:
        return False


def postgres_applied_migrations(conn: Any) -> set:
    """Return the set of recorded Postgres-only migration versions.

    Distinct from :func:`postgres_migration_version`, which returns only the
    maximum. The full set is what lets the planner spot a GAP — an optional
    migration that failed while later ones succeeded — and retry it instead of
    stranding it below the high-water mark.
    """
    try:
        rows = conn.execute("SELECT version FROM pg_migration_version").fetchall()
    except Exception:
        return set()
    return {
        int(r["version"]) for r in (rows or []) if r["version"] is not None
    }


def _apply_single_migration(conn: Any, migration: PostgresMigration) -> None:
    """Execute one migration's SQL and record the version.

    Executes against ``conn.raw`` (raw psycopg), NOT the ``_PostgresCursor``
    adapter, so migration DDL is not subject to SQLite-compat translation
    (``?`` → ``%s``, strict-mode checks, etc.).

    ``CREATE INDEX CONCURRENTLY`` requires the connection to be in autocommit
    mode. ``connect_postgres`` always opens with ``autocommit=True``, so each
    statement commits immediately — this is correct and required for
    CONCURRENTLY.

    The version INSERT runs last. If a prior statement fails the version is not
    recorded, so the migration retries on the next connect.
    """
    raw = conn.raw if hasattr(conn, "raw") else conn
    for statement in (*_schema_statements(migration.sql), *migration.raw_statements):
        if "INDEX" in statement.upper():
            logger.info(
                "pg-only migration v%d: creating index (may take a while"
                " on large tables): %.80s…",
                migration.version,
                statement,
            )
        raw.execute(statement)
    # Append-only version record. ON CONFLICT DO NOTHING makes a concurrent
    # second runner safe (both see version N, both try to insert — second wins
    # the race but the INSERT is a harmless no-op).
    raw.execute(
        "INSERT INTO pg_migration_version (version) VALUES (%s) ON CONFLICT DO NOTHING",
        (migration.version,),
    )


def apply_postgres_migrations(conn: Any) -> None:
    """Apply any pending Postgres-only migrations.

    Called by :func:`init_postgres_schema` on every connect. Reads the recorded
    versions from ``pg_migration_version`` and applies anything not yet
    recorded — including gaps below the high-water mark, so an optional
    migration that failed earlier is retried rather than stranded. Completed
    migrations do not run again; unfinished DDL and data repairs must be safe
    to replay.

    The version ``INSERT … ON CONFLICT DO NOTHING`` tolerates duplicate ledger
    writes. It does not serialize concurrent initializers' DDL, which can
    still require a retry if they race to create the same objects.

    Optional migrations (``optional=True``) log a WARNING on failure without
    recording the version, enabling retry on next connect. Non-optional
    migrations propagate the exception.
    """
    current = postgres_migration_version(conn)
    applied = postgres_applied_migrations(conn)
    pending = plan_postgres_migrations(current, applied)
    if not pending:
        return
    for migration in pending:
        if migration.optional:
            try:
                _apply_single_migration(conn, migration)
                logger.info("pg-only migration v%d applied", migration.version)
            except Exception as exc:
                logger.warning(
                    "pg-only migration v%d skipped (optional): %s",
                    migration.version,
                    exc,
                )
        else:
            _apply_single_migration(conn, migration)
            logger.info("pg-only migration v%d applied", migration.version)


def _schema_statements(sql: str):
    # These declarative scripts contain no procedural bodies or quoted
    # semicolons. Strip comments before splitting so comment prose cannot
    # accidentally become an executable statement.
    for statement in re.sub(r"--[^\n]*", "", sql).split(";"):
        if statement.strip():
            yield statement.strip()


def init_postgres_schema(conn: Any, schema_version: int) -> None:
    """Provision tables, require column parity, then build indexes and record success.

    CREATE TABLE IF NOT EXISTS leaves existing tables untouched. Indexes must
    wait for reconciliation, or an index on a newly added column prevents the
    upgrade that would have supplied that column. Required DDL failures
    propagate; callers must never serve a partially usable state store.
    """
    raw = conn.raw if hasattr(conn, "raw") else conn
    for statement in _schema_statements(_POSTGRES_TABLE_SQL):
        raw.execute(statement)
    reconcile_postgres_columns(conn, SCHEMA_SQL)
    apply_postgres_migrations(conn)
    for statement in _schema_statements(_POSTGRES_INDEX_SQL):
        raw.execute(statement)
    # Keep the shared version separate from the PostgreSQL migration ledger,
    # and never claim completion before the required schema work succeeds.
    if postgres_schema_version(conn) < schema_version:
        raw.execute(
            "INSERT INTO schema_version (version) VALUES (%s) ON CONFLICT DO NOTHING", (schema_version,)
        )
    conn.commit()


def postgres_schema_version(conn: Any) -> int:
    """Return the recorded schema version, or 0 if the schema is uninitialized."""
    try:
        row = conn.execute("SELECT MAX(version) AS version FROM schema_version").fetchone()
    except Exception:
        return 0
    if not row or row["version"] is None:
        return 0
    return int(row["version"])


def postgres_migration_version(conn: Any) -> int:
    """Return the highest applied Postgres-only migration version, else 0.

    Read from ``pg_migration_version``, which is separate from the shared
    ``schema_version`` on purpose — see the note on the table in
    SCHEMA_SQL_POSTGRES.

    Databases created before that split have no ``pg_migration_version`` row
    and fall back to 0, which replans every Postgres-only migration from the
    start. That is deliberate, and it is a repair rather than a cost:

    * Migrations use conditional DDL or replaceable definitions to preserve
      existing objects while repairing their contract. Projection repairs can
      invalidate cached fields; their ledger record prevents repeating that
      work on later connections.
    * A legacy database's ledger cannot be trusted anyway. While pg-only
      versions shared the ``schema_version`` namespace, a shared version above
      the pg-only range made every migration look applied, so they were
      skipped — and some databases carry *recorded* versions whose objects were
      never created. ``reconcile_postgres_columns`` heals missing columns but
      never creates extensions, indexes, or tables, so a trusted-but-wrong
      ledger would leave those missing permanently (no pg_trgm, no search
      indexes) with nothing to ever repair them.

    Replanning from 0 converges both cases on the same correct end state.
    """
    try:
        row = conn.execute(
            "SELECT MAX(version) AS version FROM pg_migration_version"
        ).fetchone()
    except Exception:
        return 0
    if not row or row["version"] is None:
        return 0
    return int(row["version"])


# ---------------------------------------------------------------------------
# Declarative column reconciliation (parity with SessionSchemaMixin)
# ---------------------------------------------------------------------------
#
# WHY THIS EXISTS
# ---------------
# Before this, the two backends managed schema by *different mechanisms* and
# only one was self-healing:
#
#   SQLite   — SessionSchemaMixin._reconcile_columns() diffs live columns against
#              SCHEMA_SQL on every startup and ALTER TABLE ADD COLUMNs whatever
#              is missing. Declaring a column is sufficient.
#   Postgres — a hand-maintained list of ALTER TABLE ... ADD COLUMN statements
#              in _PG_ONLY_MIGRATIONS. Declaring a column did nothing until a
#              human also wrote the matching ALTER.
#
# So the standing invariant was: *any column added to SCHEMA_SQL is automatically
# live on SQLite and silently absent on Postgres.* It failed at WARNING with a
# normal-looking turn, so it cost the deployment its entire session history before
# anyone noticed. Fixing the drifted columns alone fixes the instance; this
# function fixes the generator.
#
# SQLITE-DECLARED TYPES ON POSTGRES
# ---------------------------------
# The declared type comes from SCHEMA_SQL, i.e. SQLite's dialect, so it is
# mapped to the Postgres equivalent (_PG_TYPE_MAP) before use. Only the small
# closed set of types SCHEMA_SQL actually uses is mapped; an unrecognized type
# fails initialization rather than being guessed at: an unusable store must not
# be handed to the transcript writer.
#
# ADD COLUMN ONLY — NEVER CREATE TABLE
# ------------------------------------
# This mirrors the SQLite reconciler's contract exactly: it reconciles columns
# on tables that already exist and skips tables that do not. That is not an
# omission, it is the Chesterton's-fence boundary — ``async_delegations`` is
# declared in SCHEMA_SQL but is SQLite-local by design (tools/async_delegation.py
# opens its own raw sqlite3 connection to HERMES_HOME/state.db and never routes
# through SessionDB). A reconciler that created every declared table would
# provision tables the Postgres path never reads. Tables that genuinely belong
# on both backends are declared in SCHEMA_SQL_POSTGRES and created there.

# SQLite declared type -> Postgres equivalent. Closed set: exactly the types
# SCHEMA_SQL uses today. Anything else fails reconciliation (see above).
_PG_TYPE_MAP = {
    "TEXT": "TEXT",
    "INTEGER": "INTEGER",
    "REAL": "DOUBLE PRECISION",
    "BLOB": "BYTEA",
    "": "TEXT",  # SQLite allows a typeless column; TEXT is the safe analogue
}


def _pg_column_type(declared: str) -> Optional[str]:
    """Map a SQLite column declaration to its Postgres equivalent.

    *declared* is what ``_parse_schema_columns`` reconstructs — a base type
    optionally followed by ``NOT NULL`` and/or ``DEFAULT <expr>``. The base type
    is translated via ``_PG_TYPE_MAP``; the constraint tail is passed through
    unchanged (``NOT NULL DEFAULT 0`` is valid in both dialects).

    Returns ``None`` for an unmapped base type so the caller can refuse the
    upgrade rather than emit a guessed ADD COLUMN.
    """
    parts = declared.split()
    base = parts[0].upper() if parts else ""
    # A bare constraint keyword means the column was declared with no type.
    if base in ("NOT", "DEFAULT"):
        base, tail = "", parts
    else:
        tail = parts[1:]
    mapped = _PG_TYPE_MAP.get(base)
    if mapped is None:
        return None
    return " ".join([mapped, *tail]) if tail else mapped


def reconcile_postgres_columns(conn: Any, schema_sql: str) -> List[str]:
    """ADD any column declared in *schema_sql* that is absent from Postgres.

    The PostgreSQL analogue of ``SessionSchemaMixin._reconcile_columns``.
    Runs on every connect; idempotent. Returns the ``table.column`` names it
    added, for logging and for tests to assert on.

    Live columns are read from ``information_schema.columns`` in ONE query
    (not per-table) so the cost is a single round trip regardless of table
    count. Only tables that already exist are touched — see the module note
    above on why this never CREATEs a table.

    A missing required column that cannot be added aborts startup. Reporting
    success here would defer the error to the next transcript write.
    """
    declared = SessionSchemaMixin._parse_schema_columns(schema_sql)

    raw = conn.raw if hasattr(conn, "raw") else conn
    live: Dict[str, set] = {}
    for table_name, column_name in raw.execute(
        "SELECT table_name, column_name FROM information_schema.columns"
        " WHERE table_schema = current_schema()"
    ).fetchall():
        live.setdefault(table_name, set()).add(column_name)

    added: List[str] = []
    for table_name, columns in declared.items():
        live_cols = live.get(table_name)
        if live_cols is None:
            # Table absent on Postgres. Either SQLite-local by design
            # (async_delegations) or not yet created — creating it here is not
            # this function's job. DEBUG, not WARNING: this is the expected
            # steady state for SQLite-local tables, and warning on every
            # connect would train operators to ignore the log.
            logger.debug(
                "pg reconcile: table %s not present on Postgres, skipping",
                table_name,
            )
            continue
        for column_name, declared_type in columns.items():
            if column_name in live_cols:
                continue
            pg_type = _pg_column_type(declared_type)
            if pg_type is None:
                raise RuntimeError(
                    f"PostgreSQL schema cannot represent {table_name}.{column_name} "
                    f"with declared type {declared_type!r}"
                )
            try:
                raw.execute(
                    f'ALTER TABLE "{table_name}"'
                    f' ADD COLUMN IF NOT EXISTS "{column_name}" {pg_type}'
                )
            except Exception as exc:
                raise RuntimeError(
                    f"PostgreSQL schema could not add required column {table_name}.{column_name}"
                ) from exc
            added.append(f"{table_name}.{column_name}")

    if added:
        # INFO, not DEBUG: a column appearing here means the declarative
        # schema moved and Postgres caught up on its own. That is exactly the
        # event that was invisible before, so it gets a visible line.
        logger.info("pg reconcile: added missing columns: %s", ", ".join(added))
    return added


def init_postgres_topic_schema(conn: Any) -> None:
    """Provision topic tables only on explicit /topic opt-in or source migration."""
    from hermes_state_telegram import _TOPIC_TABLES

    raw = conn.raw if hasattr(conn, "raw") else conn
    for table, _columns, ddl in _TOPIC_TABLES:
        # SQLite REAL is a double. PostgreSQL REAL is single precision and
        # cannot preserve epoch timestamps, so spell the type explicitly.
        ddl = re.sub(r"\bREAL\b", "DOUBLE PRECISION", ddl)
        raw.execute(f"CREATE TABLE IF NOT EXISTS {table} ({ddl})")
    raw.execute(
        "CREATE UNIQUE INDEX IF NOT EXISTS idx_telegram_dm_topic_bindings_session "
        "ON telegram_dm_topic_bindings(session_id)"
    )
    raw.execute(
        "CREATE INDEX IF NOT EXISTS idx_telegram_dm_topic_bindings_user "
        "ON telegram_dm_topic_bindings(profile_name, user_id, chat_id)"
    )
