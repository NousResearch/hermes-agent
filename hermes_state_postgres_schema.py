# SQLite-compatible builtins the shared session SQL calls. The json_extract walker covers the
# path grammar production SQL uses: ``$``, ``.key``, ``[N]``, ``[#]`` (array length, extract
# returns NULL as SQLite does), ``[#-1]`` (last element). json_patch is RFC 7386 merge-patch
# with SQLite's edge semantics (NULL base -> NULL; non-object base -> replaced by the patch).
# changes() is a defensive fallback: psycopg always reports rowcount, so _write_rowcount never
# reaches it on this backend.
FUNCTION_SQL = """
CREATE FUNCTION json_valid(raw TEXT) RETURNS BOOLEAN
LANGUAGE SQL IMMUTABLE PARALLEL SAFE AS $$
    SELECT CASE WHEN raw IS JSON THEN true ELSE false END
$$;
CREATE FUNCTION json_extract(raw TEXT, path TEXT) RETURNS TEXT
LANGUAGE plpgsql IMMUTABLE PARALLEL SAFE STRICT AS $$
DECLARE
    cur JSONB;
    rest TEXT;
    seg TEXT;
    pos INTEGER;
BEGIN
    cur := raw::jsonb;
    IF length(path) < 2 OR left(path, 1) <> '$' THEN
        RAISE EXCEPTION 'unsupported JSON path: %', path;
    END IF;
    rest := substring(path from 2);
    WHILE length(rest) > 0 LOOP
        IF left(rest, 1) = '.' THEN
            pos := position('.' in substring(rest from 2));
            IF pos = 0 THEN
                pos := position('[' in substring(rest from 2));
                IF pos = 0 THEN
                    seg := substring(rest from 2);
                ELSE
                    seg := substring(rest, 2, pos - 1);
                END IF;
            ELSE
                seg := substring(rest, 2, pos - 1);
            END IF;
            IF seg = '' THEN
                RAISE EXCEPTION 'unsupported JSON path: %', path;
            END IF;
            cur := cur -> seg;
            rest := substring(rest from length(seg) + 2);
        ELSIF left(rest, 1) = '[' THEN
            pos := position(']' in rest);
            IF pos = 0 THEN
                RAISE EXCEPTION 'unsupported JSON path: %', path;
            END IF;
            seg := substring(rest, 2, pos - 2);
            IF seg = '#' THEN
                RETURN NULL;
            ELSIF seg = '#-1' THEN
                IF jsonb_typeof(cur) <> 'array' THEN
                    RETURN NULL;
                END IF;
                cur := cur -> (jsonb_array_length(cur) - 1);
            ELSIF seg ~ '^[0-9]+$' THEN
                cur := cur -> seg;
            ELSE
                RAISE EXCEPTION 'unsupported JSON path: %', path;
            END IF;
            rest := substring(rest from pos + 1);
        ELSE
            RAISE EXCEPTION 'unsupported JSON path: %', path;
        END IF;
    END LOOP;
    IF jsonb_typeof(cur) = 'string' THEN
        RETURN cur #>> '{}';
    END IF;
    RETURN cur::text;
END
$$;
CREATE FUNCTION json_type(raw TEXT, path TEXT) RETURNS TEXT
LANGUAGE SQL IMMUTABLE PARALLEL SAFE STRICT AS $$
    SELECT CASE jsonb_typeof(raw::jsonb #> string_to_array(substr(path, 3), '.'))
        WHEN 'string' THEN 'text'
        ELSE jsonb_typeof(raw::jsonb #> string_to_array(substr(path, 3), '.')) END
$$;
CREATE FUNCTION json_remove(raw TEXT, path TEXT) RETURNS TEXT
LANGUAGE SQL IMMUTABLE PARALLEL SAFE STRICT AS $$
    SELECT (raw::jsonb #- string_to_array(substr(path, 3), '.'))::text
$$;
CREATE FUNCTION json_set(raw TEXT, path TEXT, value TEXT) RETURNS TEXT
LANGUAGE SQL IMMUTABLE PARALLEL SAFE AS $$
    SELECT jsonb_set(raw::jsonb, string_to_array(substr(path, 3), '.'),
                    COALESCE(to_jsonb(value), 'null'::jsonb), true)::text
$$;
-- SQLite json_set accepts any scalar as the value; PG needs a matching argument type.
CREATE FUNCTION json_set(raw TEXT, path TEXT, value DOUBLE PRECISION) RETURNS TEXT
LANGUAGE SQL IMMUTABLE PARALLEL SAFE AS $$
    SELECT jsonb_set(raw::jsonb, string_to_array(substr(path, 3), '.'),
                    COALESCE(to_jsonb(value), 'null'::jsonb), true)::text
$$;
CREATE FUNCTION json_set(raw TEXT, path TEXT, value BIGINT) RETURNS TEXT
LANGUAGE SQL IMMUTABLE PARALLEL SAFE AS $$
    SELECT jsonb_set(raw::jsonb, string_to_array(substr(path, 3), '.'),
                    COALESCE(to_jsonb(value), 'null'::jsonb), true)::text
$$;
CREATE FUNCTION json_set(raw TEXT, path TEXT, value BOOLEAN) RETURNS TEXT
LANGUAGE SQL IMMUTABLE PARALLEL SAFE AS $$
    SELECT jsonb_set(raw::jsonb, string_to_array(substr(path, 3), '.'),
                    COALESCE(to_jsonb(value), 'null'::jsonb), true)::text
$$;
CREATE FUNCTION json_insert(raw TEXT, path TEXT, value TEXT) RETURNS TEXT
LANGUAGE plpgsql IMMUTABLE PARALLEL SAFE AS $$
DECLARE
    cur JSONB;
    v JSONB;
BEGIN
    IF raw IS NULL OR path IS NULL THEN
        RETURN NULL;
    END IF;
    cur := raw::jsonb;
    v := COALESCE(to_jsonb(value), 'null'::jsonb);
    IF path = '$[#]' THEN
        RETURN (cur || v)::text;
    END IF;
    RETURN jsonb_set(cur, string_to_array(substr(path, 3), '.'), v, false)::text;
END
$$;
CREATE FUNCTION json_patch(base TEXT, patch TEXT) RETURNS TEXT
LANGUAGE plpgsql IMMUTABLE PARALLEL SAFE AS $$
DECLARE
    b JSONB;
    p JSONB;
    k TEXT;
BEGIN
    IF base IS NULL OR patch IS NULL THEN
        RETURN NULL;
    END IF;
    p := patch::jsonb;
    b := base::jsonb;
    IF jsonb_typeof(b) <> 'object' THEN
        RETURN p::text;
    END IF;
    FOR k IN SELECT key FROM jsonb_object_keys(p) LOOP
        IF p -> k = 'null'::jsonb THEN
            b := b - k;
        ELSIF (b ? k) AND jsonb_typeof(p -> k) = 'object' THEN
            b := jsonb_set(b, array[k], json_patch(b -> k, p -> k));
        ELSE
            b := jsonb_set(b, array[k], p -> k);
        END IF;
    END LOOP;
    RETURN b::text;
END
$$;
CREATE FUNCTION json_array_length(raw TEXT, path TEXT DEFAULT '$') RETURNS BIGINT
LANGUAGE plpgsql IMMUTABLE PARALLEL SAFE STRICT AS $$
DECLARE
    cur JSONB;
    rest TEXT;
    seg TEXT;
    pos INTEGER;
BEGIN
    cur := raw::jsonb;
    rest := substring(path from 2);
    WHILE length(rest) > 0 LOOP
        pos := position('.' in substring(rest from 2));
        IF pos = 0 THEN
            seg := substring(rest from 2);
        ELSE
            seg := substring(rest, 2, pos - 1);
        END IF;
        cur := cur -> seg;
        rest := substring(rest from length(seg) + 2);
    END LOOP;
    IF cur IS NULL THEN
        RETURN NULL;
    END IF;
    IF jsonb_typeof(cur) = 'array' THEN
        RETURN jsonb_array_length(cur);
    END IF;
    RETURN 0;
END
$$;
CREATE FUNCTION json_each(raw TEXT) RETURNS TABLE(key TEXT, value TEXT)
LANGUAGE plpgsql STABLE PARALLEL SAFE AS $$
DECLARE
    kk TEXT;
    vv JSONB;
    j JSONB;
BEGIN
    IF raw IS NULL THEN
        RETURN;
    END IF;
    j := raw::jsonb;
    IF jsonb_typeof(j) = 'object' THEN
        FOR kk, vv IN SELECT je.key, je.value FROM jsonb_each(j) AS je LOOP
            key := kk;
            value := CASE WHEN jsonb_typeof(vv) = 'string' THEN vv #>> '{}' ELSE vv::text END;
            RETURN NEXT;
        END LOOP;
        RETURN;
    END IF;
    IF jsonb_typeof(j) = 'array' THEN
        FOR kk, vv IN SELECT (je.ord - 1)::text, je.value
                      FROM jsonb_array_elements(j) WITH ORDINALITY AS je(value, ord) LOOP
            key := kk;
            value := CASE WHEN jsonb_typeof(vv) = 'string' THEN vv #>> '{}' ELSE vv::text END;
            RETURN NEXT;
        END LOOP;
        RETURN;
    END IF;
    key := NULL;
    value := CASE WHEN jsonb_typeof(j) = 'string' THEN j #>> '{}' ELSE j::text END;
    RETURN NEXT;
END
$$;
-- SQLite GLOB operator form (pattern, value): * any run, ? one char, [..] a class. The
-- production patterns are single-``*`` prefixes; the full grammar is supported for parity.
CREATE FUNCTION glob(pattern TEXT, value TEXT) RETURNS BOOLEAN
LANGUAGE plpgsql IMMUTABLE PARALLEL SAFE AS $$
DECLARE
    re TEXT := '^';
    i INTEGER := 1;
    n INTEGER;
    ch TEXT;
    j INTEGER;
BEGIN
    IF pattern IS NULL OR value IS NULL THEN
        RETURN NULL;
    END IF;
    n := length(pattern);
    WHILE i <= n LOOP
        ch := substring(pattern, i, 1);
        IF ch = '*' THEN
            re := re || '.*';
        ELSIF ch = '?' THEN
            re := re || '.';
        ELSIF ch = '[' THEN
            j := position(']' in substring(pattern, i + 1));
            IF j = 0 THEN
                re := re || '\\[';
            ELSE
                re := re || '[';
                i := i + 1;
                IF substring(pattern, i, 1) = '^' THEN
                    re := re || '^';
                    i := i + 1;
                END IF;
                WHILE i <= n AND substring(pattern, i, 1) <> ']' LOOP
                    re := re || substring(pattern, i, 1);
                    i := i + 1;
                END LOOP;
                re := re || ']';
            END IF;
        ELSIF ch IN ('.', '+', '(', ')', '|', '^', '$', '{', '}', '\\') THEN
            re := re || '\\' || ch;
        ELSE
            re := re || ch;
        END IF;
        i := i + 1;
    END LOOP;
    RETURN value ~ (re || '$');
END
$$;
CREATE FUNCTION instr(haystack TEXT, needle TEXT) RETURNS INTEGER
LANGUAGE SQL IMMUTABLE PARALLEL SAFE STRICT AS $$ SELECT pg_catalog.strpos(haystack, needle) $$;
CREATE FUNCTION changes() RETURNS BIGINT
LANGUAGE SQL IMMUTABLE PARALLEL SAFE AS $$
    SELECT 0
$$;
"""

# Triggers mirror the SQLite display-identity, message-uid and transcript-revision machinery,
# plus the runtime-ledger delete guard and the PostgreSQL-only change-revision counter the
# TUI/watcher profile readers poll (the SQLite path uses file mtimes instead).
DISPLAY_SQL = """
CREATE FUNCTION messages_display_order_insert() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.display_order IS NULL THEN
        UPDATE messages SET display_order = COALESCE((
            SELECT display_order FROM messages
            WHERE session_id = NEW.session_id AND id <> NEW.id
              AND (active = 1 OR compacted = 1)
              AND display_identity = NEW.display_identity AND display_order IS NOT NULL
            ORDER BY display_order LIMIT 1
        ), NEW.id) WHERE id = NEW.id;
    END IF;
    RETURN NULL;
END
$$;
CREATE TRIGGER messages_display_order_insert AFTER INSERT ON messages
FOR EACH ROW WHEN (NEW.display_order IS NULL)
EXECUTE FUNCTION messages_display_order_insert();

CREATE FUNCTION messages_display_visibility_update() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    UPDATE messages SET display_order = LEAST(NEW.id, COALESCE((
        SELECT display_order FROM messages
        WHERE session_id = NEW.session_id AND id <> NEW.id
          AND (active = 1 OR compacted = 1)
          AND display_identity = NEW.display_identity AND display_order IS NOT NULL
        ORDER BY display_order LIMIT 1
    ), NEW.id)) WHERE id = NEW.id AND (NEW.active = 1 OR NEW.compacted = 1);
    UPDATE messages SET display_order = (SELECT display_order FROM messages WHERE id = NEW.id)
    WHERE session_id = NEW.session_id AND id <> NEW.id AND (active = 1 OR compacted = 1)
      AND display_identity = NEW.display_identity
      AND (NEW.active = 1 OR NEW.compacted = 1);
    UPDATE messages SET display_order = (
        SELECT MIN(peer.id) FROM messages AS peer
        WHERE peer.session_id = OLD.session_id AND (peer.active = 1 OR peer.compacted = 1)
          AND peer.display_identity = OLD.display_identity
    ) WHERE session_id = OLD.session_id AND (active = 1 OR compacted = 1)
      AND display_identity = OLD.display_identity
      AND NOT (NEW.active = 1 OR NEW.compacted = 1);
    RETURN NULL;
END
$$;
CREATE TRIGGER messages_display_visibility_update AFTER UPDATE OF active, compacted ON messages
FOR EACH ROW WHEN ((NEW.active = 1 OR NEW.compacted = 1) <> (OLD.active = 1 OR OLD.compacted = 1))
EXECUTE FUNCTION messages_display_visibility_update();

CREATE FUNCTION messages_display_identity_update() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    UPDATE messages SET display_identity = NULL, display_order = NULL
    WHERE id = NEW.id OR (
        session_id = OLD.session_id AND display_identity = OLD.display_identity
        AND (active = 1 OR compacted = 1)
    );
    RETURN NULL;
END
$$;
CREATE TRIGGER messages_display_identity_update
AFTER UPDATE OF role, content, timestamp, tool_call_id, tool_calls, tool_name,
                display_kind ON messages
FOR EACH ROW WHEN (NEW.role IS DISTINCT FROM OLD.role
  OR NEW.content IS DISTINCT FROM OLD.content
  OR NEW.timestamp IS DISTINCT FROM OLD.timestamp
  OR NEW.tool_call_id IS DISTINCT FROM OLD.tool_call_id
  OR NEW.tool_calls IS DISTINCT FROM OLD.tool_calls
  OR NEW.tool_name IS DISTINCT FROM OLD.tool_name
  OR NEW.display_kind IS DISTINCT FROM OLD.display_kind)
EXECUTE FUNCTION messages_display_identity_update();

CREATE FUNCTION messages_display_identity_delete() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    UPDATE messages SET display_order = (
        SELECT MIN(peer.id) FROM messages AS peer
        WHERE peer.session_id = OLD.session_id AND (peer.active = 1 OR peer.compacted = 1)
          AND peer.display_identity = OLD.display_identity
    ) WHERE session_id = OLD.session_id AND (active = 1 OR compacted = 1)
      AND display_identity = OLD.display_identity;
    RETURN NULL;
END
$$;
CREATE TRIGGER messages_display_identity_delete AFTER DELETE ON messages
FOR EACH ROW WHEN (OLD.active = 1 OR OLD.compacted = 1)
EXECUTE FUNCTION messages_display_identity_delete();

-- Every row carries a message_uid, whoever wrote it: a build that predates the column binds
-- NULL, so the store mints one on its behalf. md5(random()::text) is a core function (pgcrypto's
-- gen_random_bytes needs an extension nothing here installs) and yields the same
-- 32-lowercase-hex format as SQLite's lower(hex(randomblob(16))).
CREATE FUNCTION messages_message_uid_insert() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    UPDATE messages SET message_uid = md5(random()::text)
    WHERE id = NEW.id;
    RETURN NULL;
END
$$;
CREATE TRIGGER messages_message_uid_insert AFTER INSERT ON messages
FOR EACH ROW WHEN (NEW.message_uid IS NULL)
EXECUTE FUNCTION messages_message_uid_insert();

-- An in-place transcript rewrite moves neither the active row count nor the highest id; this
-- write-side revision is what transcript-derived caches key on.
CREATE FUNCTION messages_transcript_revision_update() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    UPDATE sessions SET transcript_revision = transcript_revision + 1
    WHERE id = NEW.session_id;
    RETURN NULL;
END
$$;
CREATE TRIGGER messages_transcript_revision_update
AFTER UPDATE OF role, content, api_content, tool_calls, tool_call_id, tool_name,
                reasoning, reasoning_content, reasoning_details ON messages
FOR EACH ROW EXECUTE FUNCTION messages_transcript_revision_update();

-- Downgrade guard, parity with the SQLite BEFORE DELETE trigger: a session with runtime
-- history cannot be deleted by a store that predates the runtime tables.
CREATE FUNCTION sessions_runtime_ledger_delete_guard() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM session_admissions WHERE target_session_id = OLD.id)
       OR EXISTS (SELECT 1 FROM worker_executions WHERE session_id = OLD.id) THEN
        RAISE EXCEPTION 'Refused to delete a session that has gateway runtime history: state.db was upgraded by a newer Hermes, and this older Hermes cannot delete such sessions. Downgrading is unsupported. Run hermes update to go back to the newer release, or restore the pre-update snapshot: https://hermes-agent.nousresearch.com/docs/getting-started/updating#rolling-back-to-an-older-release';
    END IF;
    RETURN OLD;
END
$$;
CREATE TRIGGER sessions_runtime_ledger_delete_guard BEFORE DELETE ON sessions
FOR EACH ROW EXECUTE FUNCTION sessions_runtime_ledger_delete_guard();

-- PostgreSQL-only: the TUI sidebar and web profile readers poll this revision to detect
-- cross-process writes (the SQLite path has no revision and uses file mtimes).
CREATE TABLE state_change_revision (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    revision BIGINT NOT NULL
);
INSERT INTO state_change_revision VALUES (1, 0);
CREATE FUNCTION bump_state_change_revision() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    UPDATE state_change_revision SET revision = revision + 1 WHERE id = 1;
    RETURN NULL;
END
$$;
CREATE TRIGGER sessions_changed AFTER INSERT OR UPDATE OR DELETE ON sessions
FOR EACH STATEMENT EXECUTE FUNCTION bump_state_change_revision();
CREATE TRIGGER messages_changed AFTER INSERT OR UPDATE OR DELETE ON messages
FOR EACH STATEMENT EXECUTE FUNCTION bump_state_change_revision();
"""

