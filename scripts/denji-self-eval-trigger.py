#!/usr/bin/env python3
"""P3.3 — Deterministic targeted self-evaluation trigger.

Decides WHEN a profile should be asked for a self-evaluation submission
(``denji-self-eval-submit``).  Self-evaluation is supporting evidence,
never the primary health signal — the four-dimension review (P3.2) owns
that.  A trigger fires only when one of:

  * repeated failure        — >= N failures in the quality window
  * material config change  — config.yaml/SOUL.md mtime inside window
  * quality regression      — quality verdict WATCH/ATTENTION
  * quarterly lead review   — calendar boundary (lead profiles only)

Guarantees:
  * deterministic: the same evidence state produces the same decision;
  * idempotent: emitting twice for the same (profile, reason, window)
    produces one trigger event (event_id derived from those keys);
  * no blanket fleet-wide request is ever generated by this path;
  * supports evidence must cite the reason and evidence reference;
  * never pauses/edits ``denji-self-eval-reminder`` or any cron record;
  * disposable-HERMES_HOME safe (all writes go to the given HERMES_HOME).
"""

from __future__ import annotations

import hashlib
import os
import time
from pathlib import Path
from typing import Any, List, Optional

TRIGGER_VERSION = "selfeval-trigger-1"

# Repeated-failure threshold within the quality window.
REPEATED_FAILURE_THRESHOLD = 3

TRIGGER_REASONS = (
    "repeated_failure",
    "material_config_change",
    "quality_regression",
    "quarterly_lead_review",
)

# Ledger event types counted as failure evidence (P3.2 quality dimension).
_FAILURE_EVENT_TYPES = (
    "kanban.crashed",
    "kanban.gave_up",
    "job_run_error",
    "kanban.completion_blocked_hallucination",
)

# Identity files whose mtime counts as a material configuration change.
_CONFIG_FILES = ("config.yaml", "SOUL.md")


def _ledger_counts(profile: str, since: int, hermes_home: Path) -> dict[str, int]:
    import sqlite3
    db = hermes_home / "governance" / "profile-activity-ledger.sqlite"
    if not db.exists():
        return {}
    try:
        con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
        rows = con.execute(
            "SELECT event_type, COUNT(*) FROM activity_events "
            "WHERE (actor_profile = ? OR target_profile = ?) "
            "AND occurred_at >= ? GROUP BY event_type",
            (profile, profile, int(since)),
        ).fetchall()
        con.close()
        return {r[0]: int(r[1]) for r in rows}
    except Exception:
        return {}


def _config_changed(profile: str, since: int, hermes_home: Path) -> tuple[bool, list[str]]:
    """True when an identity/config file changed inside the window."""
    profiles_dir = hermes_home / "profiles"
    base = hermes_home if profile == "default" else profiles_dir / profile
    changed: list[str] = []
    for fn in _CONFIG_FILES:
        path = base / fn
        if fn == "config.yaml" and profile == "default":
            path = hermes_home / "config.yaml"
        try:
            if path.exists() and path.stat().st_mtime >= since:
                changed.append(fn)
        except OSError:
            continue
    return bool(changed), changed


def _quality_regression(profile: str, since: int, hermes_home: Path) -> tuple[bool, dict]:
    """Read the latest review event's quality dimension verdict, if any."""
    import sqlite3
    db = hermes_home / "governance" / "profile-activity-ledger.sqlite"
    try:
        con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
        row = con.execute(
            "SELECT payload_json FROM activity_events "
            "WHERE event_type LIKE 'profile.review.%' AND target_profile = ? "
            "ORDER BY occurred_at DESC, id DESC LIMIT 1",
            (profile,),
        ).fetchone()
        con.close()
    except Exception:
        return False, {}
    if not row or not row[0]:
        return False, {}
    try:
        import json
        payload = json.loads(row[0])
        dim = (payload.get("dimensions") or {}).get("quality") or {}
        verdict = dim.get("verdict")
        return verdict in ("WATCH", "ATTENTION"), {"quality_verdict": verdict}
    except Exception:
        return False, {}


def decide_trigger(
    profile: str,
    *,
    since: int,
    now: Optional[int] = None,
    hermes_home: Optional[Path] = None,
    is_lead: bool = False,
    force_quarter_boundary: bool = False,
) -> dict[str, Any]:
    """Compute the deterministic self-eval trigger decision for a profile.

    Returns a decision dict:
        {"trigger": bool, "reasons": [...], "evidence": {...},
         "profile": ..., "trigger_version": ...}
    """
    home = Path(hermes_home) if hermes_home else Path(
        os.environ.get("HERMES_HOME", "") or Path.home() / ".hermes"
    )
    now = int(now or time.time())
    reasons: List[dict] = []
    evidence: dict[str, Any] = {
        "window_start": int(since),
        "window_end": now,
        "window_days": (now - int(since)) // 86400,
        "source_refs": ["profile-activity-ledger"],
        "trigger_version": TRIGGER_VERSION,
    }

    counts = _ledger_counts(profile, since, home)
    failures = sum(counts.get(t, 0) for t in _FAILURE_EVENT_TYPES)
    evidence["failure_events"] = failures
    if failures >= REPEATED_FAILURE_THRESHOLD:
        reasons.append({
            "reason": "repeated_failure",
            "evidence_ref": "profile-activity-ledger:failure_events",
            "count": failures,
        })

    changed, changed_files = _config_changed(profile, since, home)
    evidence["config_files_changed"] = changed_files
    if changed:
        reasons.append({
            "reason": "material_config_change",
            "evidence_ref": "file-mtime:" + ",".join(changed_files),
        })

    regression, qev = _quality_regression(profile, since, home)
    evidence.update(qev)
    if regression:
        reasons.append({
            "reason": "quality_regression",
            "evidence_ref": "profile.review.*:quality.verdict=" + str(qev.get("quality_verdict")),
        })

    if force_quarter_boundary and is_lead:
        reasons.append({
            "reason": "quarterly_lead_review",
            "evidence_ref": "calendar:quarter-boundary",
        })

    return {
        "trigger": bool(reasons),
        "reasons": reasons,
        "evidence": evidence,
        "profile": profile,
        "trigger_version": TRIGGER_VERSION,
    }


def emit_trigger(
    decision: dict[str, Any],
    *,
    hermes_home: Path,
) -> Optional[str]:
    """Append an idempotent trigger event to the ledger, if triggered.

    Event id derives from (profile, sorted reasons, window_end) so repeated
    processing of the same evidence window is idempotent.  Returns the
    event_id, or None when no trigger applies.
    """
    if not decision.get("trigger"):
        return None
    profile = decision["profile"]
    window_end = decision["evidence"]["window_end"]
    reason_keys = ",".join(sorted(r["reason"] for r in decision["reasons"]))
    digest = hashlib.sha256(
        f"{profile}|{reason_keys}|{window_end}".encode("utf-8")
    ).hexdigest()[:16]
    event_id = f"selfeval-trigger-{profile}-{digest}"
    try:
        from hermes_cli.profile_activity_ledger import append_event
        append_event(
            source="denji-self-eval-trigger",
            event_type="profile.self_eval.trigger",
            event_id=event_id,
            actor_profile="denji",
            target_profile=profile,
            object_type="profile.self_eval",
            summary=(
                "Targeted self-eval trigger for "
                f"{profile}: {reason_keys}"
            ),
            payload={
                "trigger_version": decision["trigger_version"],
                "reasons": decision["reasons"],
                "evidence": decision["evidence"],
            },
            occurred_at=int(window_end),
        )
        return event_id
    except Exception:
        return event_id


if __name__ == "__main__":
    import argparse
    import json
    ap = argparse.ArgumentParser(description="Deterministic self-eval trigger decision")
    ap.add_argument("--profile", required=True)
    ap.add_argument("--since", type=int, default=int(time.time()) - 7 * 86400)
    ap.add_argument("--emit", action="store_true", help="append the trigger event when triggered")
    ap.add_argument("--lead", action="store_true")
    args = ap.parse_args()
    decision = decide_trigger(args.profile, since=args.since, is_lead=args.lead)
    print(json.dumps(decision, indent=2))
    if args.emit and decision["trigger"]:
        home = Path(os.environ.get("HERMES_HOME", "") or Path.home() / ".hermes")
        print("event:", emit_trigger(decision, hermes_home=home) or "")