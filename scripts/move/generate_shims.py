#!/usr/bin/env python3
"""Write the shims that keep old module paths working for releases that update across a move.

For each name in ``hermes_agent/compat/required_names.py`` whose module has moved (longest dotted
prefix in ``hermes_agent/compat/moves.py``), write a file at the old path. Imported, it installs the
compat finder and becomes the moved module object. Run by path or with ``-m``, it runs the moved
module as ``__main__`` with the same argv. ``.gitattributes`` marks every shim as generated.

    python scripts/move/generate_shims.py          # write shims, delete stale ones
    python scripts/move/generate_shims.py --check  # exit 1 when the tree differs from what it would write
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from hermes_agent.compat.finder import current_name
from hermes_agent.compat.moves import MOVES
from hermes_agent.compat.required_names import REQUIRED_NAMES

HEADER = "# Generated by scripts/move/generate_shims.py; do not edit."
ATTRIBUTES = ".gitattributes"
BLOCK_BEGIN = "# BEGIN shims (generated by scripts/move/generate_shims.py; do not edit)\n"
BLOCK_END = "# END shims\n"
TEMPLATE = '''{header}
"""``{old}`` moved to ``{new}``."""
import importlib
import runpy
import sys
from pathlib import Path

if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).resolve().parents[{depth}]))

from hermes_agent.compat import install

install()
if __name__ == "__main__":
    runpy.run_module("{new}", run_name="__main__", alter_sys=True)
else:
    sys.modules[__name__] = importlib.import_module("{new}")
'''


def _old_module(name: str, kind: str) -> str:
    if kind in ("by-path", "exists"):
        parts = Path(name).with_suffix("").parts
        return ".".join(parts[:-1] if parts[-1] == "__init__" else parts)
    return name


def shims() -> dict[str, str]:
    """Repo-relative shim path -> file text, for every required name that has moved."""
    files = {}
    for name, kind in REQUIRED_NAMES.items():
        old = _old_module(name, kind)
        new = current_name(old, MOVES)
        if new is None:
            continue
        target = ROOT.joinpath(*new.split("."))
        if (target / "__init__.py").is_file():
            path = Path(*old.split("."), "__init__.py")
        elif target.with_suffix(".py").is_file():
            path = Path(*old.split(".")).with_suffix(".py")
        else:
            raise SystemExit(f"generate_shims: {old} moved to {new}, which is not in the tree")
        if kind in ("by-path", "exists"):
            path = Path(name)
        files[path.as_posix()] = TEMPLATE.format(header=HEADER, old=old, new=new, depth=len(path.parts) - 1)
    return files


def attributes(paths: list[str]) -> str:
    text = (ROOT / ATTRIBUTES).read_text(encoding="utf-8-sig")
    head, begin, rest = text.partition(BLOCK_BEGIN)
    _, end, tail = rest.partition(BLOCK_END)
    if not (begin and end):
        raise SystemExit(f"generate_shims: {ATTRIBUTES} has no shim block ({BLOCK_BEGIN.strip()} ... {BLOCK_END.strip()})")
    return head + BLOCK_BEGIN + "".join(f"/{p} linguist-generated=true\n" for p in sorted(paths)) + BLOCK_END + tail


def strays(expected: dict[str, str]) -> list[str]:
    """Files that are not shims but carry the header, or sit in a moved package's old folder."""
    listed = subprocess.run(["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"], cwd=ROOT,
                            capture_output=True, text=True, check=True, stdin=subprocess.DEVNULL, timeout=120).stdout
    found = []
    for rel in sorted(set(listed.split("\0")) - set(expected) - {""}):
        path = ROOT / rel
        if not path.is_file():
            continue
        folder = ".".join(Path(rel).parent.parts)
        moved_folder = bool(folder) and current_name(folder, MOVES) is not None
        if moved_folder or (rel.endswith(".py") and _is_shim(path)):
            found.append(rel)
    return found


def _is_shim(path: Path) -> bool:
    with path.open(encoding="utf-8-sig", errors="replace") as handle:
        return handle.readline().rstrip("\n") == HEADER


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="change nothing; exit 1 when the tree differs")
    args = parser.parse_args(argv)
    files = shims()
    stale = strays(files)
    files[ATTRIBUTES] = attributes([p for p in files if p != ATTRIBUTES])
    changed = [rel for rel, text in files.items()
               if not (ROOT / rel).is_file() or (ROOT / rel).read_text(encoding="utf-8-sig") != text]
    if args.check:
        for rel in changed:
            print(f"{rel}: differs from what scripts/move/generate_shims.py writes; run it")
        for rel in stale:
            print(f"{rel}: stray: has the shim header or sits in a moved folder, but is not a shim")
        return 1 if changed or stale else 0
    for rel in changed:
        (ROOT / rel).parent.mkdir(parents=True, exist_ok=True)
        (ROOT / rel).write_text(files[rel], encoding="utf-8", newline="\n")
        print(f"wrote {rel}")
    kept = []
    for rel in stale:
        if _is_shim(ROOT / rel):
            (ROOT / rel).unlink()
            print(f"deleted {rel}")
        else:
            kept.append(rel)
            print(f"{rel}: in a moved folder but not a shim; move or delete it")
    return 1 if kept else 0


if __name__ == "__main__":
    raise SystemExit(main())
