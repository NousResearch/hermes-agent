#!/usr/bin/env bash
# Install Hermes from an offline payload archive. No network, no curl|bash.
#
# This is the air-gapped half of the offline handoff:
#
#   connected machine:  hermes pm bundle --out <payload> && \
#                       python3 scripts/offline/pack.py --payload <payload> --out <transfer> --verify
#   air-gapped machine: ./scripts/offline/install.sh --archive <transfer>/hermes-offline-<target>.tar.gz
#
# It deliberately does not clone, resolve, or download anything: the payload
# already contains the repo snapshot, the standalone interpreter, the native
# tool store, the sealed PM runtime, a built venv, and a lock-scoped wheel
# cache. Installing is unpacking that tree, checking it, and putting the
# launchers on PATH.
#
# Requires bash (3.2+) and tar. Nothing else is assumed to exist.
set -euo pipefail

ARCHIVE=""
MANIFEST=""
DEST="${HERMES_INSTALL_DIR:-$HOME/.hermes}"
LINK_DIR="${HERMES_BIN_DIR:-$HOME/.local/bin}"
VERIFY=1
WRITE_SHELL=1
DRY_RUN=0

usage() {
    cat <<'EOF'
usage: install.sh --archive <payload.tar.gz> [options]

  --archive PATH   the payload archive produced by scripts/offline/pack.py (required)
  --manifest PATH  the matching .manifest.json (default: <archive>.manifest.json sibling,
                   or <archive-without-.tar.gz>.manifest.json)
  --dest DIR       where to unpack the payload (default: $HERMES_INSTALL_DIR or ~/.hermes)
  --bin-dir DIR    where to link the hermes launchers (default: ~/.local/bin)
  --no-verify      skip digest verification (NOT recommended; disables the transfer check)
  --no-shell       do not add ~/.local/bin to your shell rc files
  --dry-run        print what would happen, change nothing
  -h, --help       this message
EOF
}

log()  { printf '  %s\n' "$*"; }
step() { printf '\n==> %s\n' "$*"; }
fail() { printf '\nerror: %s\n' "$*" >&2; exit 1; }

while [ $# -gt 0 ]; do
    case "$1" in
        --archive)   ARCHIVE="${2:-}"; shift 2 ;;
        --manifest)  MANIFEST="${2:-}"; shift 2 ;;
        --dest)      DEST="${2:-}"; shift 2 ;;
        --bin-dir)   LINK_DIR="${2:-}"; shift 2 ;;
        --no-verify) VERIFY=0; shift ;;
        --no-shell)  WRITE_SHELL=0; shift ;;
        --dry-run)   DRY_RUN=1; shift ;;
        -h|--help)   usage; exit 0 ;;
        *)           usage >&2; fail "unknown argument: $1" ;;
    esac
done

[ -n "$ARCHIVE" ] || { usage >&2; fail "--archive is required"; }
[ -f "$ARCHIVE" ] || fail "archive not found: $ARCHIVE"
ARCHIVE="$(cd "$(dirname "$ARCHIVE")" && pwd)/$(basename "$ARCHIVE")"

command -v tar >/dev/null 2>&1 || fail "tar is required"

# ---------------------------------------------------------------- manifest ---
if [ -z "$MANIFEST" ]; then
    for candidate in "$ARCHIVE.manifest.json" "${ARCHIVE%.tar.gz}.manifest.json"; do
        [ -f "$candidate" ] && MANIFEST="$candidate" && break
    done
fi
[ -n "$MANIFEST" ] && [ -f "$MANIFEST" ] || fail \
    "no manifest found next to the archive; pass --manifest, or transfer the .manifest.json too"

# jq is not assumed to exist. The manifest is generated by pack.py with
# sort_keys, so these reads are key lookups on one-line values; a missing key
# reads as empty and is reported as a malformed manifest.
manifest_value() {
    sed -n "s/.*\"$1\"[[:space:]]*:[[:space:]]*\"\([^\"]*\)\".*/\1/p" "$MANIFEST" | head -1
}
manifest_number() {
    sed -n "s/.*\"$1\"[[:space:]]*:[[:space:]]*\([0-9][0-9]*\).*/\1/p" "$MANIFEST" | head -1
}

PACK_KIND="$(manifest_value kind)"
TARGET="$(manifest_value target)"
EXPECTED_SUM="$(manifest_value archiveSha256)"
EXPECTED_BYTES="$(manifest_number archiveBytes)"
ARCHIVE_NAME="$(manifest_value archive)"

[ "$PACK_KIND" = "hermes-offline-payload" ] || fail \
    "$MANIFEST is not an offline payload manifest (kind='$PACK_KIND')"

# ------------------------------------------------------------------ digests ---
# Hash before extracting: a corrupt or substituted archive must never reach the
# filesystem. sha256sum (Linux) and shasum (macOS) are both accepted.
hash_file() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | awk '{print $1}'
    elif command -v shasum >/dev/null 2>&1; then
        shasum -a 256 "$1" | awk '{print $1}'
    elif command -v openssl >/dev/null 2>&1; then
        openssl dgst -sha256 "$1" | awk '{print $NF}'
    else
        return 1
    fi
}

step "Payload archive"
log "archive:  $ARCHIVE"
log "target:   ${TARGET:-unknown}"
log "manifest: $MANIFEST"

if [ "$VERIFY" = 1 ]; then
    if [ -z "$EXPECTED_SUM" ]; then
        fail "manifest records no archiveSha256; re-pack with digests, or pass --no-verify to override"
    fi
    if ! actual_sum="$(hash_file "$ARCHIVE")"; then
        fail "no SHA-256 tool found (need sha256sum, shasum, or openssl)"
    fi
    [ "$actual_sum" = "$EXPECTED_SUM" ] || fail \
        "archive digest mismatch
       expected: $EXPECTED_SUM
       actual:   $actual_sum
     The transfer is corrupt or the archive does not match this manifest."
    log "sha256:   ok"
    if [ -n "$EXPECTED_BYTES" ]; then
        actual_bytes="$(wc -c < "$ARCHIVE" | tr -d ' ')"
        [ "$actual_bytes" = "$EXPECTED_BYTES" ] || fail \
            "archive size mismatch (expected $EXPECTED_BYTES bytes, got $actual_bytes)"
    fi
else
    log "sha256:   SKIPPED (--no-verify)"
fi

# ------------------------------------------------------------------ extract ---
# The archive holds a single top-level directory (its arcname is the payload
# directory name), so extraction yields one relocatable tree.
step "Extracting into $DEST"
if [ "$DRY_RUN" = 1 ]; then
    log "would extract $ARCHIVE into $DEST"
    log "would link launchers into $LINK_DIR"
    exit 0
fi

mkdir -p "$DEST"
STAGE="$DEST/.offline-stage.$$"
rm -rf "$STAGE"
mkdir -p "$STAGE"
cleanup() { rm -rf "$STAGE"; }
trap cleanup EXIT

tar -xzf "$ARCHIVE" -C "$STAGE" || fail "extraction failed"

# Resolve payload root: the single directory at the stage root.
set -- "$STAGE"/*
[ "$#" -eq 1 ] || fail "archive must contain exactly one top-level directory, found $#"
PAYLOAD="$1"
[ -f "$PAYLOAD/manifest.json" ] || fail "extracted payload has no manifest.json"
[ -x "$PAYLOAD/bin/hermes" ] || fail "extracted payload has no runnable bin/hermes"

# A payload pins the interpreter, wheels and native binaries of the machine
# that built it. Installing a mismatched target produces an install that fails
# later in confusing ways, so refuse it here.
log "payload target: $(sed -n 's/.*"target"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' "$PAYLOAD/manifest.json" | head -1)"

PAYLOAD_DIR="$DEST/payload"
if [ -e "$PAYLOAD_DIR" ]; then
    # Never delete a previous payload in place: it may be the only working
    # install on the machine, and a failed upgrade must leave it runnable.
    retire="$DEST/payload.previous-$(date -u +%Y%m%d-%H%M%S)"
    log "moving existing payload aside to $(basename "$retire")"
    mv "$PAYLOAD_DIR" "$retire" || fail "could not move the existing payload aside"
fi
mv "$PAYLOAD" "$PAYLOAD_DIR" || fail "could not publish the payload to $PAYLOAD_DIR"
rm -rf "$STAGE"
trap - EXIT

# ---------------------------------------------------------------- launchers ---
# Symlinks into the payload's own shims, matching how the desktop bundles
# publish commands. An existing entry is replaced only when it is ours (a
# symlink into our payload) or missing/dangling; a user's own hermes from
# pipx or another checkout is never clobbered.
step "Publishing commands"
mkdir -p "$LINK_DIR"
for name in hermes hermes-agent hermes-acp; do
    source="$PAYLOAD_DIR/bin/$name"
    [ -f "$source" ] || continue
    target="$LINK_DIR/$name"
    if [ -L "$target" ]; then
        current="$(readlink "$target" 2>/dev/null || true)"
        case "$current" in
            *"/payload/bin/$name"|"") : ;;
            *) log "keeping existing $target (not ours)"; continue ;;
        esac
    elif [ -e "$target" ]; then
        log "keeping existing $target (not a symlink)"; continue
    fi
    ln -sfn "$source" "$target"
    log "linked $target -> $source"
done

# -------------------------------------------------------------------- verify ---
step "Verifying the install runs"
if [ -x "$LINK_DIR/hermes" ]; then
    HERMES_CMD="$LINK_DIR/hermes"
else
    HERMES_CMD="$PAYLOAD_DIR/bin/hermes"
fi
if version="$(HERMES_HOME="${HERMES_HOME:-$DEST/hermes-home}" PYTHONUTF8=1 "$HERMES_CMD" --version 2>&1)"; then
    printf '%s\n' "$version" | sed 's/^/  /'
else
    fail "the payload was extracted but '$HERMES_CMD --version' failed:
$version"
fi

# ---------------------------------------------------------------------- path ---
if [ "$WRITE_SHELL" = 1 ]; then
    step "Shell PATH"
    case ":$PATH:" in
        *":$LINK_DIR:"*) log "$LINK_DIR is already on PATH" ;;
        *)
            line="case \":\$PATH:\" in *\":$LINK_DIR:\"*) ;; *) export PATH=\"$LINK_DIR:\$PATH\" ;; esac"
            pattern="^[[:space:]]*([^#[:space:]].*)?PATH=.*$(printf '%s' "$LINK_DIR" | sed 's/[.[\*^$]/\\&/g')"
            wrote=0
            for rc in "$HOME/.bashrc" "$HOME/.profile" "$HOME/.zshrc" "$HOME/.zprofile"; do
                [ -e "$rc" ] || continue
                if grep -Eq "$pattern" "$rc" 2>/dev/null; then
                    log "$rc already sets PATH"; wrote=1; continue
                fi
                printf '\n%s\n' "$line" >> "$rc" && { log "added $LINK_DIR to PATH in $rc"; wrote=1; }
            done
            [ "$wrote" = 1 ] || log "add '$LINK_DIR' to your PATH to run 'hermes'"
            ;;
    esac
fi

step "Done"
log "payload:  $PAYLOAD_DIR"
log "commands: $LINK_DIR/hermes"
cat <<EOF

  Open a new shell (or 'export PATH="$LINK_DIR:\$PATH"') and run:

      hermes --version

  This install is offline by construction: it contains its interpreter, tools
  and wheels, and does not contact the network at runtime.
EOF
