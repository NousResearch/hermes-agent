#!/usr/bin/env -S bash -c 'exec "$BASH" "$(dirname "$0")/run-in-hermes-env" python3 "$0" "$@"'
"""Rewrite ``tools/connectors/portal/catalog_snapshot.py`` from the Nous Portal's hosted catalog.

The Portal's catalog route needs a signed-in token, so run this from a signed-in install before a
release::

    python scripts/refresh_connector_catalog.py
"""

from __future__ import annotations

import pprint
import sys
from datetime import date
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from tools.connectors.portal.client import PortalConnectorClient

TARGET = REPO_ROOT / "tools" / "connectors" / "portal" / "catalog_snapshot.py"

HEADER = '''"""The hosted connector catalog, served while there is no Nous identity yet, so opening the
Connectors page lists the apps without creating one. Generated by
``scripts/refresh_connector_catalog.py`` on {day}; do not edit by hand."""

CATALOG = '''


def main() -> int:
    # Logos are left out: no client draws them, and their host is the Portal's to change.
    rows = [row.model_dump(by_alias=True, exclude={"logo_url"}) for row in PortalConnectorClient().catalog().connectors]
    body = pprint.pformat(tuple(sorted(rows, key=lambda row: row["slug"])), width=119, sort_dicts=False)
    TARGET.write_text(HEADER.format(day=date.today().isoformat()) + body + "\n", encoding="utf-8")
    print(f"Wrote {len(rows)} connectors to {TARGET.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
