#!/usr/bin/env bash
# prove_disk_guard_node_modules_scope.sh
#
# Regression guard for the node_modules sweep in disk-guard.sh, added after the
# 2026-09-24 ENOSPC incident (8 agent review clones in $HOME held 4.3Gi of
# node_modules while the guard reported "the remaining consumers are NOT agent
# scratch").
#
# Two failure modes, both measured on 2026-09-24 during that fix:
#   TOO NARROW — the sweep never saw $HOME-level agent clones at all.
#   TOO BROAD  — a first cut selected ~/workspace/<repo>/node_modules (a human
#                checkout), ~/.local/lib/node_modules (global npm prefix, holds
#                the pi/opencode CLIs) and ~/.hermes/hermes-agent/node_modules
#                (the running agent itself).
#
# 2026-09-25, review round 1: this harness USED TO re-implement the selection
# predicate in its own words and assert against that copy. It therefore stayed
# green for a full day while the real sweep was absent from the script
# entirely, and it would stay green if the real exclusions drifted. It now
# drives the guard's REAL reclaim_home_node_modules through the
# DISK_GUARD_LIB=1 seam against a sandboxed $HOME, so the test cannot drift
# from the code it protects. There is no local copy of the predicate here.
#
# Everything happens inside a private throwaway $HOME; the real home is never
# touched. Run: bash ~/.hermes/scripts/tests/prove_disk_guard_node_modules_scope.sh
set -uo pipefail

GUARD="${DISK_GUARD:-$HOME/.hermes/scripts/disk-guard.sh}"
FAIL=0
ok()   { printf 'PASS  %s\n' "$*"; }
bad()  { printf 'FAIL  %s\n' "$*"; FAIL=1; }

grep -q 'reclaim_home_node_modules' "$GUARD" \
  && ok "guard contains the node_modules sweep" \
  || bad "guard has no node_modules sweep — the 2026-09-24 class fix is gone"

bash -n "$GUARD" && ok "guard parses" || bad "guard has a syntax error"

FIX=$(mktemp -d -t dgscope)
AGED=202001010000

# TOO NARROW fixture: an agent review clone sitting directly under $HOME.
mkdir -p "$FIX/agent-clone/node_modules"; git init -q "$FIX/agent-clone"
# ...and one a level deeper, i.e. $HOME/<dir>/<repo>/.git (parent-of-repos form).
mkdir -p "$FIX/reviews/repo/node_modules"; git init -q "$FIX/reviews/repo"
# TOO BROAD fixtures: everything the narrowing exists to protect.
mkdir -p "$FIX/workspace/humanrepo/node_modules"; git init -q "$FIX/workspace/humanrepo"
mkdir -p "$FIX/Library/app/node_modules";        git init -q "$FIX/Library/app"
mkdir -p "$FIX/.local/lib/node_modules"
mkdir -p "$FIX/.hermes/hermes-agent/node_modules"; git init -q "$FIX/.hermes/hermes-agent"
# Liveness fixture: an aged, otherwise-selectable clone with a live pid inside.
mkdir -p "$FIX/busy-clone/node_modules"; git init -q "$FIX/busy-clone"

find "$FIX" -type d -name node_modules -exec touch -t "$AGED" {} +

( cd "$FIX/busy-clone/node_modules" && exec sleep 300 ) &
INUSE_PID=$!
sleep 1

# Drive the guard's REAL function against the sandboxed HOME.
HOME="$FIX" bash -c '
    set -uo pipefail
    DISK_GUARD_LIB=1 source "'"$GUARD"'"
    reclaim_home_node_modules
  ' >"$FIX/sweep.log" 2>&1

# Anti-vacuity: if the seam broke, the sweep never ran and every "kept"
# assertion below would pass for the wrong reason.
grep -q 'node_modules: removed' "$FIX/sweep.log" \
  && ok "the real reclaim_home_node_modules actually executed" \
  || bad "sweep did not run (library seam broken) — the keeps below are vacuous"

for gone in agent-clone/node_modules reviews/repo/node_modules; do
  [ -d "$FIX/$gone" ] \
    && bad "TOO NARROW: $gone survived the sweep" \
    || ok "evicts \$HOME agent clone $gone"
done

for keep in workspace/humanrepo/node_modules Library/app/node_modules \
            .local/lib/node_modules .hermes/hermes-agent/node_modules; do
  [ -d "$FIX/$keep" ] \
    && ok "excludes $keep" \
    || bad "TOO BROAD: deleted $keep"
done

if kill -0 "$INUSE_PID" 2>/dev/null && [ -d "$FIX/busy-clone/node_modules" ]; then
  ok "keeps a clone held open by a live process"
else
  bad "TOO BROAD: deleted a node_modules dir with a live process inside it"
fi

kill "$INUSE_PID" 2>/dev/null
wait "$INUSE_PID" 2>/dev/null
rm -rf "$FIX"

[ "$FAIL" = 0 ] && { echo "=== RESULT: PASS ==="; exit 0; }
echo "=== RESULT: FAIL ==="; exit 1
