#!/usr/bin/env python3
"""
Setup wizard for watch-video skill.
Checks dependencies and creates config file.
"""
from __future__ import annotations
import subprocess
import sys
import shutil
from pathlib import Path
import json


def check_command(cmd: list[str], name: str, version_flag: str = "--version") -> tuple[bool, str]:
    """Check if command exists and get version."""
    try:
        result = subprocess.run(cmd + [version_flag], capture_output=True, text=True, timeout=10, check=False)
        if result.returncode == 0:
            version = result.stdout.strip().split("\n")[0]
            return True, version
        return False, f"Command failed: {result.stderr.strip()}"
    except FileNotFoundError:
        return False, "Not found in PATH"
    except subprocess.TimeoutExpired:
        return False, "Timed out"
    except Exception as e:
        return False, str(e)


def check_ollama_model(ollama_url: str, model: str) -> tuple[bool, str]:
    """Check if Ollama is running and model supports vision."""
    import urllib.request
    import urllib.error

    try:
        # Check Ollama is reachable
        req = urllib.request.Request(f"{ollama_url}/api/tags", method="GET")
        with urllib.request.urlopen(req, timeout=5) as resp:
            if resp.status != 200:
                return False, f"Ollama returned status {resp.status}"

        # Check model capabilities
        data = json.dumps({"name": model}).encode()
        req = urllib.request.Request(
            f"{ollama_url}/api/show",
            data=data,
            headers={"Content-Type": "application/json"},
            method="POST",
        )
        with urllib.request.urlopen(req, timeout=10) as resp:
            if resp.status != 200:
                return False, f"Model check returned status {resp.status}"
            model_info = json.loads(resp.read().decode())

        # Check vision capability
        caps = model_info.get("capabilities", [])
        if isinstance(caps, list) and "vision" in caps:
            return True, f"Model '{model}' supports vision"
        # Check model_info for vision.block_count
        model_info_dict = model_info.get("model_info", {})
        if any("vision.block_count" in str(k).lower() for k in model_info_dict.keys()):
            return True, f"Model '{model}' supports vision (via model_info)"

        return False, f"Model '{model}' does NOT support vision (capabilities: {caps})"

    except urllib.error.URLError as e:
        return False, f"Cannot reach Ollama at {ollama_url}: {e}"
    except json.JSONDecodeError:
        return False, "Invalid JSON response from Ollama"
    except Exception as e:
        return False, f"Error checking model: {e}"


def main():
    print("=" * 60)
    print("watch-video skill — Setup Wizard")
    print("=" * 60)

    checks = []

    # 1. ffmpeg
    ok, msg = check_command(["ffmpeg", "-version"], "ffmpeg")
    checks.append(("ffmpeg", ok, msg))
    print(f"  ffmpeg:       {'✓' if ok else '✗'} {msg}")

    # 2. ffprobe
    ok, msg = check_command(["ffprobe", "-version"], "ffprobe")
    checks.append(("ffprobe", ok, msg))
    print(f"  ffprobe:      {'✓' if ok else '✗'} {msg}")

    # 3. yt-dlp
    ok, msg = check_command(["yt-dlp", "--version"], "yt-dlp")
    checks.append(("yt-dlp", ok, msg))
    print(f"  yt-dlp:       {'✓' if ok else '✗'} {msg}")

    # 4. Python version
    py_version = f"{sys.version_info.major}.{sys.version_info.minor}.{sys.version_info.micro}"
    ok = sys.version_info >= (3, 9)
    checks.append(("Python 3.9+", ok, py_version))
    print(f"  Python:       {'✓' if ok else '✗'} {py_version}")

    # 5. Ollama + vision model
    ollama_url = "http://localhost:11434"
    vision_model = "qwen3-vl:4b"
    ok, msg = check_ollama_model(ollama_url, vision_model)
    checks.append((f"Ollama ({vision_model})", ok, msg))
    print(f"  Ollama:       {'✓' if ok else '✗'} {msg}")

    print()
    all_ok = all(c[1] for c in checks)

    if all_ok:
        print("✓ All dependencies satisfied!")
    else:
        print("✗ Some dependencies missing:")
        for name, ok, msg in checks:
            if not ok:
                print(f"  - {name}: {msg}")
        print()
        print("Install missing dependencies:")
        print("  macOS:  brew install ffmpeg yt-dlp")
        print("  Linux:  apt install ffmpeg && pipx install yt-dlp")
        print("  Windows: winget install Gyan.FFmpeg yt-dlp.yt-dlp")
        print("  Ollama: ollama pull qwen3-vl:4b && ollama serve")

    # Create config file
    config_dir = Path.home() / ".hermes" / "skills" / "config"
    config_dir.mkdir(parents=True, exist_ok=True)
    config_path = config_dir / "watch-video.yaml"

    config_content = f"""# watch-video skill configuration
# Generated by setup wizard — edit as needed
ollama_url: "{ollama_url}"
vision_model: "{vision_model}"
vision_timeout: 120
vision_batch_size: 8
default_max_frames: 80
default_resolution: 512
output_dir: "~/.hermes/watch-video-notes"
cache_dir: "~/.hermes/cache/watch-video"
"""

    if not config_path.exists():
        config_path.write_text(config_content)
        print(f"\nCreated config: {config_path}")
    else:
        print(f"\nConfig exists (not overwritten): {config_path}")
        print("Edit manually if needed.")

    # Create .env.example
    env_example = Path(__file__).parent.parent / ".env.example"
    env_content = f"""# watch-video skill environment variables
# Copy to .env and customize, or set in shell
OLLAMA_BASE_URL={ollama_url}
WATCH_VIDEO_VISION_MODEL={vision_model}
WATCH_VIDEO_OUTPUT_DIR=~/.hermes/watch-video-notes
"""
    env_example.write_text(env_content)
    print(f"Created .env.example: {env_example}")

    return 0 if all_ok else 1


if __name__ == "__main__":
    sys.exit(main())