"""Automatic background review must not treat compaction-summary carriers as user evidence.

``role=user`` on a Hermes compaction handoff is transport compatibility, not authorship: the
body was generated by Hermes, so an unattended memory-capable review fork must not see it as
candidate evidence for durable memory writes. These tests drive the real
``AIAgent._spawn_background_review`` -> fork ``run_conversation`` boundary and assert on the
``conversation_history`` the review model would actually see.
"""

