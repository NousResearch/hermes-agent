_SUMMARY_MARKER = "SUMMARY_ONLY_PREF_7f3a9"
_TAIL_MARKER = "TAIL_DIRECT_STATEMENT_2b8c1"
_LIVE_MERGED_MARKER = "LIVE_MERGED_ASK_4d5e6"

# Carriers a real snapshot can carry: every frozen prefix generation (byte-pinned upstream),
# and a metadata-marked row whose text matches none of them.
_STANDALONE_CARRIER_CONTENTS = [
    pytest.param(prefix, id=name)
    for name, prefix in (
        [("current", SUMMARY_PREFIX), ("legacy", LEGACY_SUMMARY_PREFIX)]
        + [(f"historical-{i}", p) for i, p in enumerate(_HISTORICAL_SUMMARY_PREFIXES)]
    )
]


def _summary_body() -> str:
    return (
        "\n## Historical Task Snapshot\n"
        f"User asked: always deploy with {_SUMMARY_MARKER} enabled.\n\n"
        "## Resolved State\nCompleted earlier.\n\n" + _SUMMARY_END_MARKER
    )


def _carrier(prefix: str, marked: bool = True) -> dict:
    row = {
        "role": "user",
        "content": prefix + _summary_body(),
    }
    if marked:
        row[COMPRESSED_SUMMARY_METADATA_KEY] = True
    return row


def _row_text(row) -> str:
    """All text a review model would see in one replayed history row."""
    if not isinstance(row, dict):
        return str(row)
    return bg._msg_text(row)


def _history_text(history) -> str:
    return "\n".join(_row_text(row) for row in history or [])


def _snapshot_with_carrier(carrier: dict) -> list:
    return [
        {"role": "user", "content": "set up the staging deploy"},
        {"role": "assistant", "content": "staging deploy is configured"},
        carrier,
        {"role": "assistant", "content": "handoff noted"},
        {"role": "user", "content": f"please keep using {_TAIL_MARKER} for these checks"},
    ]


class _ImmediateThread:
    def __init__(self, *, target, daemon=None, name=None):
        self._target = target

    def start(self):
        self._target()


