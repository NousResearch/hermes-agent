"""/review re-review rounds: a later /review re-checks the earlier findings and the new diff.

The earlier round is built with the real async-delegation completion formatter, so the test pins
the shape a finished review actually has when it re-enters the conversation.
"""

import json
from types import SimpleNamespace

from agent import review_engine as re_mod
from agent.review_engine import build_review_task, prior_review_results, snapshot_recent_messages, start_review
from tools.process_registry_notifications import _format_async_delegation


_NOTE = "\n\n[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user.]"


def _completed_review(summary: str, status: str = "completed", batch: bool = True, excerpt=None) -> dict:
    """A finished review as it re-enters the chat: /review dispatches a one-task batch (the shape a
    live CLI stores); the single-task shape is the same notification without ``results``."""
    snap = snapshot_recent_messages(excerpt or [{"role": "assistant", "content": "x" * 11_000}])
    goal, context = build_review_task(snap)
    evt = {"delegation_id": "deleg_1", "goal": goal, "context": context, "dispatched_at": 1.0,
           "role": "leaf", "model": "m"}
    if batch:
        evt.update(goals=[goal], results=[{"task_index": 0, "status": status, "summary": summary,
                                           "live_transcript": "/scratch/task-0.log"}])
    else:
        evt.update(status=status, summary=summary)
    return {"role": "user", "content": _format_async_delegation(evt) + _NOTE}


def test_second_review_quotes_round_one_findings_and_scopes_to_the_delta(monkeypatch):
    import tools.delegate_tool as dt

    sent = {}

    def fake_delegate_task(goal, context, **_kw):
        sent.update(goal=goal, context=context)
        return json.dumps({"status": "dispatched", "delegation_id": "deleg_2"})

    monkeypatch.setattr(dt, "delegate_task", fake_delegate_task)
    monkeypatch.setattr(re_mod, "_load_review_credentials_cfg", lambda: None)
    finding = "1 blocking issue. B1: tools/x.py:12 drops the lease on retry."
    messages = [
        {"role": "user", "content": "open the PR"},
        {"role": "assistant", "content": "PR #5 opened at abc123"},
        _completed_review(finding),
        {"role": "assistant", "content": "Fixed B1 in def456"},
    ]
    start_review(SimpleNamespace(ephemeral_system_prompt=""), messages)

    assert sent["goal"] == "Review recent work"  # the worker label is the same every round
    assert "Review round 2." in sent["context"] and re_mod._REREVIEW_RULES in sent["context"]
    # Left in the excerpt, the round-1 message (briefing + 11k excerpt) loses its result to the 12k cap.
    assert f"--- Review round 1 result ---\n{finding}" in sent["context"]
    assert "x" * 1000 not in sent["context"] and "Fixed B1 in def456" in sent["context"]
    assert "live transcript" not in sent["context"] and "INTERNAL NOTIFICATION" not in sent["context"]
    single = _completed_review(finding, batch=False)
    assert prior_review_results([single]) == [finding]


def test_first_review_and_failed_earlier_review_are_round_one():
    messages = [{"role": "user", "content": "review this"}, _completed_review("partial", status="error"),
                _completed_review("partial", status="error", batch=False)]
    assert prior_review_results(messages) == []
    goal, context = build_review_task(snapshot_recent_messages(messages), "", None, prior_review_results(messages))
    assert goal == "Review recent work"
    assert "Review round 1." in context and "at most 5 nits" in context
    assert re_mod._REREVIEW_RULES not in context


def test_delegation_completion_quoted_in_the_excerpt_is_not_the_review_result():
    other = {"role": "user", "content": _format_async_delegation(
        {"delegation_id": "deleg_0", "goal": "Run the tests", "context": "ctx", "status": "completed",
         "summary": "UNRELATED: 40 tests passed"})}
    excerpt = [{"role": "user", "content": "open the PR"}, other]
    finding = "1 blocking issue. B1: tools/x.py:12 drops the lease on retry."
    for batch in (True, False):
        assert prior_review_results([other, _completed_review(finding, batch=batch, excerpt=excerpt)]) == [finding]
        failed = _completed_review("partial", status="error", batch=batch, excerpt=excerpt)
        assert prior_review_results([failed]) == []
