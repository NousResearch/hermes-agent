"""Contextual OTP discovery executes generated inspection/probe/fill, never reads source."""
import json
import subprocess
from unittest.mock import Mock

import pytest

from agent.vault_login_classifier import (
    LoginControl, build_fill_js, build_inspection_js, build_otp_probe_js, classify_otp_controls,
)


def inspect_fixture(instruction, labels=("Code",), *, visible=True, same_form=True):
    # A minimal DOM contract harness: execute the production JS in Node, not a
    # Python reimplementation of its recognition. No browser or vault state.
    fixture = {"instruction": instruction, "labels": labels, "visible": visible, "sameForm": same_form}
    script = r'''
const vm = require('node:vm');
const data = JSON.parse(process.argv[1]);
const context = JSON.parse(process.argv[2]);
const instruction = {innerText: context.instruction, visible: context.visible,
  getClientRects() { return this.visible ? [1] : []; }};
const form = {querySelectorAll() { return context.sameForm ? [instruction] : []; }};
const inputs = context.labels.map((label, i) => ({
  type: 'text', tagName: 'INPUT', id: 'floatingLabelInput' + i, name: '', autocomplete: '',
  labels: [{textContent: label}], form, maxLength: -1,
  getClientRects() { return [1]; }, getAttribute() { return ''; },
  setAttribute(k,v) {this[k] = v;}, removeAttribute(k) {delete this[k];},
  focus() {}, dispatchEvent() {},
}));
const document = {forms: [form], querySelectorAll(sel) {
  if (sel === 'input, select') return inputs;
  return inputs.filter(el => sel.includes(el['data-hermes-vault-slot']));
}, getElementById() {return null;}};
const sandbox = {document, window: {location: {origin:'https://example.test'}},
 getComputedStyle: el => ({display:'block', visibility:el.visible === false ? 'hidden':'visible'}),
 HTMLInputElement: {prototype: {}} , InputEvent: class {}, Event: class {}};
vm.createContext(sandbox);
const probe = vm.runInContext(data.probe, sandbox);
const controls = JSON.parse(vm.runInContext(data.inspect, sandbox));
const result = data.fill ? JSON.parse(vm.runInContext(data.fill, sandbox)) : null;
console.log(JSON.stringify({probe,controls,result}));
'''
    result = subprocess.run(["node", "-e", script,
                             json.dumps({"inspect": build_inspection_js("fixture"), "probe": build_otp_probe_js(),
                                         "fill": build_fill_js([{"index": 0, "token": "one-time-code", "value": "synthetic"}],
                                                               "https://other.test", "fixture")}),
                             json.dumps(fixture)], capture_output=True, text=True, check=True)
    return json.loads(result.stdout)


@pytest.mark.parametrize("instruction,labels,visible,same_form,expected", [
    ("Enter the code generated by your authenticator app", ("Code",), True, True, True),
    ("Enter your verification code", ("Code",), True, True, True),
    ("ONE-TIME code", ("Code",), True, True, True),
    ("Enter a coupon code", ("Code",), True, True, False),
    ("", ("Code",), True, True, False),
    ("Enter authenticator code", ("Promo code",), True, True, False),
    ("Enter authenticator code", ("Code",), False, True, False),
    ("Enter authenticator code", ("Code",), True, False, False),
    ("Enter authenticator code", ("Code", "Code"), True, True, False),
])
def test_contextual_probe_and_classifier_agree(instruction, labels, visible, same_form, expected):
    result = inspect_fixture(instruction, labels, visible=visible, same_form=same_form)
    controls = classify_otp_controls([LoginControl.from_dict(c) for c in result["controls"]])
    assert bool(controls) is expected
    assert result["probe"] is expected
    assert result["result"]["refused"] == "origin_changed"


