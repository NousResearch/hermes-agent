"""Fake relay connector at its network boundary, for composed recovery tests.

Two halves, both faked only at the wire:

* the ``/relay`` WebSocket is a real ``websockets`` server. It checks the
  ``Authorization`` HMAC bearer against the secret it issued, closes 4401 like
  the real connector when the bearer is missing or wrong, and otherwise answers
  ``hello`` with a descriptor and every ``outbound`` with a success result;
* the connector's HTTP routes (``POST /relay/provision``, ``POST /relay/media``)
  are served by an ``urllib.request.urlopen`` stub that replays a per-route
  script. A scripted error raises the same ``HTTPError`` (status, parsed
  headers, readable body) that urllib raises for a real HTTP error, so the code
  under test sees exactly what a proxy's 403 page looks like.

Everything between those two boundaries is production code: provisioning,
``register_relay_adapter``'s factory, ``RelayAdapter``, ``WebSocketRelayTransport``
and ``RelayMediaClient``.
"""

from __future__ import annotations

import base64
import hashlib
import hmac
import http.client
import io
import json
import urllib.error
import urllib.request
from typing import Any, Callable, Optional

import websockets

PROXY_403_BODY = (
    b"<!DOCTYPE html><html><head><title>ERROR: The requested URL could not be retrieved</title>"
    b"</head><body><p>Unable to determine IP address from host name (ERR_DNS_FAIL)</p>"
    b"<p>Generated by egress-proxy (squid/6.10)</p></body></html>"
)


def proxy_403() -> dict:
    """An egress proxy's own refusal: HTML page, proxy headers, never reached the relay."""
    return {
        "status": 403,
        "headers": {
            "Server": "squid/6.10",
            "X-Squid-Error": "ERR_DNS_FAIL 0",
            "Via": "1.1 egress-proxy (squid/6.10)",
            "Content-Type": "text/html;charset=utf-8",
        },
        "body": PROXY_403_BODY,
    }


def relay_refusal(status: int, reason: str) -> dict:
    """A refusal authored by the connector itself: JSON ``{"error": reason}``."""
    return {"status": status, "headers": {"Content-Type": "application/json"},
            "body": json.dumps({"error": reason}).encode()}


def store_unavailable() -> dict:
    return relay_refusal(503, "media store unavailable")


OK = {"status": "ok"}


def json_proxy_403(**headers: str) -> dict:
    """A JSON-emitting hop (Cloudflare/Envoy style) refusing on its own: an ``{"error"}``
    body like the connector's, but a response header names the hop."""
    return {"status": 403, "headers": {"Content-Type": "application/json", **headers},
            "body": json.dumps({"error": "upstream dns timeout"}).encode()}


def echoing(status: int, template: str) -> Callable[[str], dict]:
    """A hop that echoes the request's bearer into its body (``{token}`` in ``template``)."""
    return lambda token: {"status": status, "headers": {"Content-Type": "application/json"},
                          "body": template.replace("{token}", token).encode()}


def _http_error(url: str, spec: dict) -> urllib.error.HTTPError:
    raw = "".join(f"{k}: {v}\r\n" for k, v in spec["headers"].items()) + "\r\n"
    headers = http.client.parse_headers(io.BytesIO(raw.encode("latin-1")))
    return urllib.error.HTTPError(url, spec["status"], "error", headers, io.BytesIO(spec["body"]))


class _Resp:
    def __init__(self, status: int, payload: dict) -> None:
        self.status = status
        self._body = json.dumps(payload).encode()
        self.headers = {"Content-Type": "application/json"}

    def read(self, *_a) -> bytes:
        return self._body

    def __enter__(self):
        return self

    def __exit__(self, *_a) -> bool:
        return False


class FakeConnector:
    """See the module docstring. ``start()`` on the loop that will host the adapter."""

    def __init__(self, platform: str = "slack") -> None:
        self.platform = platform
        self.secret: Optional[str] = None
        self.gateway_id: Optional[str] = None
        self.provision_script: list[dict] = []
        self.media_script: list[dict] = []
        self.provision_calls = 0
        self.media_calls = 0
        # Every Authorization header value seen on HTTP routes (to prove logs never carry them).
        self.bearers_seen: list[str] = []
        self.ws_auth: list[str] = []  # "ok" / "rejected" per WS upgrade
        self.outbound: list[dict] = []
        self.url = ""
        self._server: Any = None

    # ── WebSocket half ──────────────────────────────────────────────────
    async def start(self) -> None:
        self._server = await websockets.serve(self._handle, "127.0.0.1", 0)
        port = next(iter(self._server.sockets)).getsockname()[1]
        self.url = f"ws://127.0.0.1:{port}/relay"

    async def stop(self) -> None:
        if self._server is not None:
            self._server.close()
            await self._server.wait_closed()

    def bearer_valid(self, header: Optional[str]) -> bool:
        if not (self.secret and header and header.startswith("Bearer ")):
            return False
        padded = header[len("Bearer "):] + "=" * (-len(header) % 4)
        try:
            payload, exp, sig = base64.urlsafe_b64decode(padded).decode().rsplit(":", 2)
        except Exception:
            return False
        want = hmac.new(self.secret.encode(), f"{payload}:{exp}".encode(), hashlib.sha256).hexdigest()
        return payload == self.gateway_id and hmac.compare_digest(want, sig)

    async def _handle(self, ws) -> None:
        if not self.bearer_valid(ws.request.headers.get("Authorization")):
            self.ws_auth.append("rejected")
            await ws.close(code=4401, reason="unauthorized")
            return
        self.ws_auth.append("ok")
        async for raw in ws:
            for line in str(raw).split("\n"):
                if line.strip():
                    await self._on_frame(ws, json.loads(line))

    async def _on_frame(self, ws, frame: dict) -> None:
        if frame.get("type") == "hello":
            descriptor = {
                "contract_version": 1, "platform": frame.get("platform") or self.platform,
                "label": "Slack", "max_message_length": 4000, "supports_draft_streaming": False,
                "supports_edit": True, "supports_threads": True, "markdown_dialect": "slack_mrkdwn",
                "len_unit": "chars", "supported_ops": ["send", "edit", "typing", "send_media"],
            }
            await ws.send(json.dumps({"type": "descriptor", "descriptor": descriptor}) + "\n")
        elif frame.get("type") == "outbound":
            action = frame.get("action", {})
            self.outbound.append(action)
            result = {"success": True, "message_id": f"ts-{len(self.outbound)}"}
            await ws.send(json.dumps({"type": "outbound_result", "requestId": frame["requestId"],
                                      "result": result}) + "\n")

    def ops(self, op: str) -> list[dict]:
        return [a for a in self.outbound if a.get("op") == op]

    # ── HTTP half (urlopen boundary) ────────────────────────────────────
    def install_http(self, monkeypatch) -> None:
        real_urlopen = urllib.request.urlopen

        def urlopen(req, timeout=None, **kw):
            url = req.full_url if isinstance(req, urllib.request.Request) else str(req)
            base = self.url.replace("ws://", "http://").removesuffix("/relay")
            if not url.startswith(base):
                return real_urlopen(req, timeout=timeout, **kw)
            path = url[len(base):]
            auth = req.get_header("Authorization") or ""
            self.bearers_seen.append(auth)
            if path == "/relay/provision":
                return self._provision(url, req, auth)
            if path == "/relay/media":
                return self._media(url, auth)
            raise AssertionError(f"unexpected connector route {path}")

        monkeypatch.setattr(urllib.request, "urlopen", urlopen)

    @staticmethod
    def _next(script: list, auth: str):
        spec = script.pop(0) if script else OK
        # A callable spec builds its answer from the bearer the request carried (``echoing``).
        return spec(auth.removeprefix("Bearer ")) if callable(spec) else spec

    def _provision(self, url: str, req, auth: str) -> _Resp:
        self.provision_calls += 1
        spec = self._next(self.provision_script, auth)
        if spec is not OK:
            raise _http_error(url, spec)
        body = json.loads(req.data.decode())
        self.gateway_id = body["gatewayId"]
        self.secret = self.secret or "s" * 64
        return _Resp(200, {"secret": self.secret, "deliveryKey": "d" * 64, "tenant": "tenant-ops",
                           "gatewayId": self.gateway_id, "routeKeys": body.get("routeKeys", [])})

    def _media(self, url: str, auth: str) -> _Resp:
        self.media_calls += 1
        spec = self._next(self.media_script, auth)
        if spec is not OK:
            raise _http_error(url, spec)
        if not self.bearer_valid(auth):
            raise _http_error(url, relay_refusal(401, "unauthenticated; per-gateway bearer required"))
        return _Resp(201, {"id": f"m-{self.media_calls}", "size": 1})
