class TestHomeScopedRefreshMechanism:
    """The scoped refresh compares/rewrites through the home-scoped plist
    machinery; the ONLY safe way to bind a sibling home in the updater is the
    context-local override (never os.environ — the updater process keeps running
    against the invoking profile, and threads read its env concurrently)."""

    def test_scopes_home_by_contextvar_and_restores_it(self, monkeypatch, tmp_path):
        from hermes_cli import gateway_launchd as launchd
        from hermes_constants import get_hermes_home_override

        sibling_home = tmp_path / "root" / "profiles" / "sib"
        sibling_home.mkdir(parents=True)
        plist = tmp_path / "LaunchAgents" / "ai.hermes.gateway-sib.plist"
        plist.parent.mkdir(parents=True, exist_ok=True)
        plist.write_text("<stale/>", encoding="utf-8")
        env_home_before = os.environ.get("HERMES_HOME")

        monkeypatch.setattr(gw, "get_launchd_plist_path", lambda: plist)
        monkeypatch.setattr(gw, "launchd_plist_is_current", lambda: False)
        seen = {}

        def fake_generate():
            seen["override"] = get_hermes_home_override()
            return "<fresh/>"

        monkeypatch.setattr(gw, "generate_launchd_plist", fake_generate)
        monkeypatch.setattr(gw, "_refuse_temp_home_service_write", lambda *a: False)
        monkeypatch.setattr(gw, "_prepare_service_launcher", lambda **k: None)
        monkeypatch.setattr("gateway.status.get_running_pid", lambda *a, **k: None)
        monkeypatch.setattr(gw, "_retry_launchctl_bootstrap_until_registered", lambda *a, **k: True)
        launchctl_calls = []
        monkeypatch.setattr(
            launchd.subprocess, "run",
            lambda cmd, **kw: launchctl_calls.append(cmd)
            or SimpleNamespace(returncode=0, stdout="", stderr=""))

        assert gw.refresh_launchd_plist_for_label(
            "ai.hermes.gateway-sib", sibling_home, domain=f"gui/{UID}") == gw.REFRESH_PLIST_RELOADED

        # The comparison/generation ran with the SIBLING's home bound…
        assert seen["override"] == str(sibling_home)
        # …the plist was rewritten…
        assert plist.read_text(encoding="utf-8") == "<fresh/>"
        # …launchd was reloaded in the domain the caller located, not the cached one…
        assert launchctl_calls[0] == ["launchctl", "bootout", f"gui/{UID}/ai.hermes.gateway-sib"]
        # …and the process environment was never touched (updater scope survives).
        assert os.environ.get("HERMES_HOME") == env_home_before
        assert get_hermes_home_override() is None

