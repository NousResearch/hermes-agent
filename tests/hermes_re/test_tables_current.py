"""The shipped Unicode delta table is the one this interpreter and this google-re2 need.

``hermes_re/_tables.py`` is generated by ``scripts/gen_hermes_re_tables.py``. A Python with another
Unicode version, or an RE2 build with other Unicode data (the same google-re2 version linked to a
libre2 built with RE2_USE_ICU answers ``\\p{..}`` from ICU), needs a regenerated entry: without it
`\\w` / `\\d` silently follow RE2's tables. This computes the entry for this interpreter and this
build's Unicode generation afresh and compares.
"""
import importlib.util
import unicodedata

from hermes_re import _tables
from tests.hermes_re._support import REPO_ROOT

SCRIPT = REPO_ROOT / "scripts" / "gen_hermes_re_tables.py"


def _generator():
    spec = importlib.util.spec_from_file_location("gen_hermes_re_tables", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_the_shipped_table_equals_a_fresh_computation_for_this_interpreter():
    generator = _generator()
    version = unicodedata.unidata_version
    shipped = _tables.TABLES.get(version)
    assert shipped is not None, f"no table for Unicode {version}: run python scripts/gen_hermes_re_tables.py"
    fresh = generator.compute()
    assert generator.same(shipped, fresh), (
        f"stale or missing entry for Unicode {version}, RE2 generation {fresh['generation']}: "
        "run python scripts/gen_hermes_re_tables.py")
    assert generator.compute(predicates=True) == fresh  # the str predicates are stdlib's `\\w \\d \\s`


def test_rendering_the_recorded_tables_reproduces_the_shipped_module():
    import json

    generator = _generator()
    recorded = json.loads(generator.JSON_PATH.read_text(encoding="utf-8"))
    namespace = {}
    exec(generator.render(recorded), namespace)  # the generated module is data only
    assert namespace["TABLES"] == _tables.TABLES
