"""The import's one check of the request (``limits.validate_patch``) agrees with the real plane.

Each body of ``plane_patch_cases.cases()`` carries gateway-gateway's own verdict
(``plane_patch_verdicts.json``, generated by its ``parseProfilePatch`` and router order through node;
the file records the commit). ``validate_patch``'s first violation is the plane's error code, and it
takes what the plane takes, except where it is deliberately stricter (:data:`STRICTER`): there the
plane accepts the bytes but stores something else (null for a number beyond a double, U+FFFD for
bytes that are not UTF-8 or a lone surrogate). With ``HERMES_TEST_GATEWAY_GATEWAY`` naming a
gateway-gateway checkout (``node_modules`` installed) and node on PATH, the verdicts are also
recomputed from that checkout and must equal the fixture's.
"""
from __future__ import annotations

import json
import os
import shutil
from pathlib import Path

import pytest

from plugins.secret_store.remote import limits
from tests.plugins.secret_store import plane_patch_cases

FIXTURE = json.loads(plane_patch_cases.FIXTURE.read_text(encoding="utf-8-sig"))
CASES = plane_patch_cases.cases()
STRICTER = {"number_overflow", "number_negative_overflow", "number_int_beyond_double", "value_not_utf8",
            "value_lone_surrogate_escape", "record_lone_surrogate_escape"}


def _verdict(data: bytes) -> str:
    found = limits.validate_patch(data)
    return found[0].code if found else "ok"


def test_the_fixture_holds_the_planes_verdict_on_exactly_these_bodies():
    assert {cid: plane_patch_cases.digest(b) for cid, b in CASES} == \
        {cid: case["sha256"] for cid, case in FIXTURE["cases"].items()}
    assert len(CASES) == len(FIXTURE["cases"]) > 100
    assert all(FIXTURE["cases"][cid]["plane"] == "ok" for cid in STRICTER)


@pytest.mark.parametrize(("cid", "data"), CASES, ids=[cid for cid, _b in CASES])
def test_the_import_check_agrees_with_the_plane(cid, data):
    plane, ours = FIXTURE["cases"][cid]["plane"], _verdict(data)
    if cid in STRICTER:
        assert ours != "ok", cid
    else:
        assert ours == plane, (cid, ours, plane)


def test_the_verdicts_are_the_checkouts():
    checkout = os.environ.get("HERMES_TEST_GATEWAY_GATEWAY", "")
    if not (checkout and shutil.which("node") and (Path(checkout) / "node_modules").is_dir()):
        pytest.skip("HERMES_TEST_GATEWAY_GATEWAY (a gateway-gateway checkout with node_modules) and node needed")
    verdicts = plane_patch_cases.plane_verdicts(Path(checkout), [b for _cid, b in CASES])
    assert dict(zip([cid for cid, _b in CASES], verdicts)) == \
        {cid: case["plane"] for cid, case in FIXTURE["cases"].items()}
