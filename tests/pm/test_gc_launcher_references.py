"""GC keeps store interpreters referenced by real Hermes launchers.

Regression coverage for #146823. Launcher files are generated by the real
writers; GC sees their interpreter paths, not a simulated reference record.
"""

from __future__ import annotations

import base64
import io
import json
import os
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

import pytest

from hermes_cli import _launchers
from pm.cli import _gc_store
from pm import filesystem
from pm.lock import Facts
from pm.store import Store


@pytest.fixture
def launcher_gc_env(tmp_path, monkeypatch):
    home = tmp_path / "hermes"
    root = home / "hermes-agent"
    store = home / "tools"
    root.mkdir(parents=True)
    store.mkdir(parents=True)
    monkeypatch.setattr(Path, "home", lambda: tmp_path)
    monkeypatch.setenv("HERMES_HOME", str(home))
    monkeypatch.setenv("HERMES_INSTALL_ROOT", str(root))
    monkeypatch.delenv("HERMES_RUNTIME_DIR", raising=False)
    if os.name == "nt":
        monkeypatch.setenv("LOCALAPPDATA", str(tmp_path))
    (store / "facts.json").write_text(
        json.dumps({"schema": 1, "packages": {"python": {"entry": "python-current"}}}),
        encoding="utf-8",
    )
    return home, root.resolve(), store


def _entry(store: Path, name: str, executable: Path) -> Path:
    entry = store / name
    entry.mkdir()
    interpreter = entry / ("python.exe" if os.name == "nt" else "bin/python3")
    interpreter.parent.mkdir(parents=True, exist_ok=True)
    if os.name == "nt":
        shutil.copy2(executable, interpreter)
    else:
        interpreter.symlink_to(executable)
        interpreter.chmod(0o755)
    return interpreter


def _write_cmd(target: Path, python: Path, root: Path) -> None:
    encoded = base64.b64encode(
        _launchers._launcher_script(target.stem, root, None).encode("utf-8")
    ).decode("ascii")
    target.write_text(
        f'@echo off\r\n"{python}" -I -c '
        f'"import base64; exec(base64.b64decode(\'{encoded}\'))" %*\r\n',
        encoding="utf-8",
    )


def _write_exe(target: Path, python: Path, root: Path) -> None:
    payload = io.BytesIO()
    with zipfile.ZipFile(payload, "w") as archive:
        archive.writestr("__main__.py", _launchers._launcher_script(target.stem, root, None))
    target.write_bytes(b"MZ" + b"\0" * 64 + b"#!" + str(python).encode() + b" -I\r\n" + payload.getvalue())


def _write_orphan(store: Path) -> None:
    (store / "python-orphan").mkdir()


def test_gc_normalizes_windows_verbatim_store_prefix():
    # Store.root is verbatim on Windows; launcher interpreter paths are native.
    from pathlib import PureWindowsPath

    verbatim = PureWindowsPath(r"\\?\C:\Users\user\AppData\Local\hermes\tools")
    native_store = PureWindowsPath(filesystem.native(verbatim))
    launcher_python = native_store / "python-old" / "python.exe"
    assert any(
        parent == native_store
        for parent in launcher_python.parents
    )
    assert native_store != verbatim


@pytest.mark.platforms("posix")
@pytest.mark.parametrize("location", ["home", "local"])
def test_gc_preserves_posix_launcher_interpreter_and_launches(launcher_gc_env, location):
    home, root, store = launcher_gc_env
    old_python = _entry(store, "python-old", Path(sys._base_executable).resolve())
    _entry(store, "python-current", Path(sys._base_executable).resolve())
    out = home / "bin" if location == "home" else root / ".hermes/bin"
    out.mkdir(parents=True, exist_ok=True)
    launcher = _launchers.mint_launcher(
        "hermes", root, out, old_python, None
    )
    _write_orphan(store)

    removed, kept = _gc_store(Store(store), Facts(store / "facts.json"))

    assert removed == 1 and kept == 2
    assert old_python.is_file()
    assert (store / "python-current").is_dir()
    assert not (store / "python-orphan").exists()
    assert launcher is not None
    assert _launchers._launcher_python(launcher) == old_python
    probe = root / "hermes_cli" / "main.py"
    probe.parent.mkdir()
    probe.write_text("import sys; sys.exit(23)\n", encoding="utf-8")
    (root / "hermes_bootstrap.py").write_text("", encoding="utf-8")
    (root / "hermes_constants.py").write_text(
        "def get_default_hermes_root():\n"
        "    from pathlib import Path\n"
        f"    return Path({str(home)!r})\n",
        encoding="utf-8",
    )
    assert subprocess.run([launcher, "--version"], check=False).returncode == 23


@pytest.mark.parametrize("location", ["home", "local"])
@pytest.mark.parametrize("form", ["cmd", "exe"])
def test_gc_preserves_windows_launcher_interpreter(launcher_gc_env, location, form):
    home, root, store = launcher_gc_env
    old_python = _entry(store, "python-old", Path(sys._base_executable).resolve())
    _entry(store, "python-current", Path(sys._base_executable).resolve())
    out = home / "bin" if location == "home" else root / ".hermes/bin"
    out.mkdir(parents=True, exist_ok=True)
    target = out / f"hermes.{form}"
    writer = _write_cmd if form == "cmd" else _write_exe
    writer(target, old_python, root)
    assert _launchers._launcher_python(target) == old_python
    _write_orphan(store)

    removed, kept = _gc_store(Store(store), Facts(store / "facts.json"))

    assert removed == 1 and kept == 2
    assert old_python.is_file()
    assert not (store / "python-orphan").exists()


def test_gc_ignores_foreign_launcher_and_external_python(launcher_gc_env):
    home, _root, store = launcher_gc_env
    python = Path(sys._base_executable).resolve()
    _entry(store, "python-current", python)
    foreign = home / "bin"
    foreign.mkdir()
    if os.name == "nt":
        (foreign / "hermes.cmd").write_text(f'@"{python}" -I -c "print(1)" %*\r\n', encoding="utf-8")
    else:
        (foreign / "hermes").write_text(f'#!/bin/sh\nexec {python} -I -c "print(1)"\n', encoding="utf-8")
    _write_orphan(store)

    removed, kept = _gc_store(Store(store), Facts(store / "facts.json"))

    assert removed == 1 and kept == 1
    assert not (store / "python-orphan").exists()
