def test_postgres_migrations_record_to_their_own_ledger(pg_schema):
    init_postgres_schema(pg_schema, SCHEMA_VERSION)
    shared_before = postgres_schema_version(pg_schema)
    version = postgres_migration_version(pg_schema) + 1
    migration = PostgresMigration(version, "CREATE TABLE IF NOT EXISTS migration_probe(id INTEGER)")
    _apply_single_migration(pg_schema, migration)
    _apply_single_migration(pg_schema, migration)
    assert postgres_migration_version(pg_schema) == version
    assert postgres_schema_version(pg_schema) == shared_before
    assert pg_schema.execute("SELECT COUNT(*) FROM pg_migration_version WHERE version = ?", (version,)).fetchone()[0] == 1


def test_migration_planning_ignores_a_newer_shared_schema_version(pg_schema):
    init_postgres_schema(pg_schema, SCHEMA_VERSION)
    pg_schema.execute("DELETE FROM pg_migration_version")
    future_shared = SCHEMA_VERSION + max(m.version for m in _PG_ONLY_MIGRATIONS) + 1
    pg_schema.execute("INSERT INTO schema_version VALUES (?)", (future_shared,))
    apply_postgres_migrations(pg_schema)
    assert {m.version for m in _PG_ONLY_MIGRATIONS if not m.optional} <= postgres_applied_migrations(pg_schema)
    assert postgres_schema_version(pg_schema) == future_shared
    init_postgres_schema(pg_schema, SCHEMA_VERSION)
    assert postgres_schema_version(pg_schema) == future_shared


def test_failed_optional_migration_is_retried_below_high_water_mark(pg_schema, monkeypatch):
    import hermes_state_pg_schema as schema

    pg_schema.execute("CREATE TABLE pg_migration_version(version INTEGER NOT NULL UNIQUE)")
    migrations = [
        PostgresMigration(1, "CREATE TABLE IF NOT EXISTS optional_probe(id INTEGER)", optional=True),
        PostgresMigration(2, "CREATE TABLE IF NOT EXISTS required_probe(id INTEGER)"),
    ]
    monkeypatch.setattr(schema, "_PG_ONLY_MIGRATIONS", migrations)
    pg_schema.fail_on = "CREATE TABLE IF NOT EXISTS optional_probe"
    apply_postgres_migrations(pg_schema)
    assert postgres_applied_migrations(pg_schema) == {2}
    pg_schema.fail_on = None
    apply_postgres_migrations(pg_schema)
    assert postgres_applied_migrations(pg_schema) == {1, 2}
    assert {"optional_probe", "required_probe"} <= set(_columns(pg_schema.db))


