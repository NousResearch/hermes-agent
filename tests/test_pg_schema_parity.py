def test_projection_upgrade_invalidates_existing_cached_fields_only_once(pg_schema):
    init_postgres_schema(pg_schema, SCHEMA_VERSION)
    pg_schema.execute("INSERT INTO sessions(id, source, started_at) VALUES ('history', 'cli', 1.0)")
    pg_schema.execute("INSERT INTO messages(id, session_id, role, content, timestamp) "
                      "VALUES (1, 'history', 'user', 'canonical history', 2.0)")
    projection_version = next(m.version for m in _PG_ONLY_MIGRATIONS if m.raw_statements)
    pg_schema.execute("DELETE FROM pg_migration_version WHERE version = ?", (projection_version,))
    pg_schema.execute(
        "UPDATE messages SET display_identity = ?, display_order = ?, fts_content = ?", (b"stale", 99, "stale text"),
    )
    init_postgres_schema(pg_schema, SCHEMA_VERSION)
    assert tuple(pg_schema.execute(
        "SELECT content, display_identity, display_order, fts_content FROM messages"
    ).fetchone()) == ("canonical history", None, None, None)
    assert projection_version in postgres_applied_migrations(pg_schema)

    # Reopening needs neither trigger-owner permissions nor another archive-wide
    # backfill after the projection migration succeeded.
    rebuilt = (b"rebuilt", 1, "rebuilt vector")
    pg_schema.execute("UPDATE messages SET display_identity = ?, display_order = ?, fts_content = ?", rebuilt)
    pg_schema.fail_on = "CREATE OR REPLACE"
    init_postgres_schema(pg_schema, SCHEMA_VERSION)
    assert tuple(pg_schema.execute(
        "SELECT display_identity, display_order, fts_content FROM messages"
    ).fetchone()) == rebuilt
