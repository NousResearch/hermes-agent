def _open_pipe_client(pipe_name: str, k32, desired_access: int) -> int:
    handle = k32.CreateFileW(
        pipe_name,
        desired_access,
        0,  # no sharing
        None,
        OPEN_EXISTING,
        0,
        None,
    )
    if handle in (None, ctypes.c_void_p(-1).value, 0xFFFFFFFFFFFFFFFF):
        raise OSError(
            f"failed to open named pipe {pipe_name} (error {ctypes.get_last_error()})"
        )
    return handle


def _build_handle_list(k32, handles) -> "tuple[ctypes.c_void_p, int]":
    """Create a PROC_THREAD_ATTRIBUTE_HANDLE_LIST attribute list."""
    size = ctypes.c_size_t()
    k32.InitializeProcThreadAttributeList(None, 1, 0, ctypes.byref(size))
    buf = ctypes.create_string_buffer(size.value)
    if not k32.InitializeProcThreadAttributeList(buf, 1, 0, ctypes.byref(size)):
        raise OSError(
            f"InitializeProcThreadAttributeList failed (error {ctypes.get_last_error()})"
        )
    arr = (wintypes.HANDLE * len(handles))(*handles)
    if not k32.UpdateProcThreadAttribute(
        buf,
        0,
        PROC_THREAD_ATTRIBUTE_HANDLE_LIST,
        ctypes.cast(arr, ctypes.c_void_p),
        ctypes.sizeof(arr),
        None,
        None,
    ):
        k32.DeleteProcThreadAttributeList(buf)
        raise OSError(
            f"UpdateProcThreadAttribute failed (error {ctypes.get_last_error()})"
        )
    return buf, 0


def main(argv: "list[str]") -> int:
    # argv: [helper, control_pipe_name, output_pipe_name, nonce]
    if len(argv) < 4:
        return 2
    control_name, output_name, nonce = argv[1], argv[2], argv[3]

    k32 = _kernel32()
    h_control = None
    h_output = None
    job: "_JobBinding | None" = None
    h_cmd = None
    h_cmd_thread = None
    attr_list = None
    cmd_path = None

    try:
        cmd_path = system_cmd_path()

        h_control = _open_pipe_client(control_name, k32, GENERIC_READ | GENERIC_WRITE)
        h_output = _open_pipe_client(output_name, k32, GENERIC_WRITE)
        k32.SetHandleInformation(h_output, HANDLE_FLAG_INHERIT, HANDLE_FLAG_INHERIT)

        # Announce the connection; the parent verifies this client PID before
        # sending anything.  The helper reports its OWN pid (os.getpid());
        # the parent cross-checks it against GetNamedPipeClientProcessId.
        # NOTE: sys.executable on a venv is the venvlauncher shim, so the
        # process handle returned by ShellExecuteExW may be the LAUNCHER's
        # pid while the real helper runs as its child — hence the helper
        # reports the pid that actually opened the pipe.
        _write_message(
            h_control,
            {"kind": KIND_CONNECTED, "v": PROTOCOL_VERSION, "nonce": nonce,
             "pid": os.getpid()},
            k32,
        )

        # Wait for the request (bounded).
        request = None
        deadline = time.monotonic() + _REQUEST_WAIT_MS / 1000.0
        while time.monotonic() < deadline:
            # Peek for a message without blocking forever.
            avail = wintypes.DWORD()
            ok = k32.PeekNamedPipe(h_control, None, 0, None, ctypes.byref(avail), None)
            if ok and int(avail.value) > 0:
                request = _read_message(h_control, k32)
                break
            time.sleep(0.05)
        if request is None:
            _write_message(
                h_control,
                {"kind": KIND_CANCELLED, "v": PROTOCOL_VERSION, "terminated": False,
                 "error": "request timeout"},
                k32,
            )
            return 5
        validate_parent_message(request, nonce)
        command = request["command"]
        cwd = request.get("cwd")
        env = request.get("env") or {}

        # --- create the real command process ------------------------------
        # The shell is the absolute system path; the first command-line token
        # is the same absolute path (Windows quoting rule), then /d /s /c.
        quoted_cmd = '"' + cmd_path + '"'
        cmdline = f"{quoted_cmd} /d /s /c {command}"
        cmd_buf = ctypes.create_unicode_buffer(cmdline)
        env_block = _build_env_block(env)

        # stdout/stderr: the ONLY inheritable handles (STARTUPINFOEXW +
        # handle list).  hStdInput is NULL: elevated commands are non-
        # interactive.
        si_ex = _STARTUPINFOEXW()
        si_ex.StartupInfo.cb = ctypes.sizeof(_STARTUPINFOEXW)
        si_ex.StartupInfo.dwFlags = STARTF_USESTDHANDLES
        si_ex.StartupInfo.hStdInput = None
        si_ex.StartupInfo.hStdOutput = h_output
        si_ex.StartupInfo.hStdError = h_output

        attr_list, _ = _build_handle_list(k32, [h_output, h_output])
        si_ex.lpAttributeList = ctypes.cast(attr_list, ctypes.c_void_p)

        # Create the child SUSPENDED: it must be assigned to the job (with
        # KILL_ON_JOB_CLOSE) BEFORE it runs a single instruction, so a
        # grandchild spawned immediately on startup is still inside the job
        # and dies with the tree on timeout.  The job is created and bound
        # in this window; only then is the thread resumed.
        pi = _PROCESS_INFORMATION()
        ok = k32.CreateProcessW(
            cmd_path,  # lpApplicationName: absolute, never searched
            cmd_buf,
            None,
            None,
            True,  # bInheritHandles: allowlist via PROC_THREAD_ATTRIBUTE_HANDLE_LIST
            CREATE_UNICODE_ENVIRONMENT | CREATE_NO_WINDOW | CREATE_SUSPENDED,
            env_block,
            cwd,
            ctypes.byref(si_ex),
            ctypes.byref(pi),
        )
        if not ok:
            err = ctypes.get_last_error()
            _write_message(
                h_control,
                {"kind": KIND_DONE, "v": PROTOCOL_VERSION, "nonce": nonce,
                 "rc": -1, "job_bound": False, "child_pid": None,
                 "error": f"CreateProcessW failed ({err})"},
                k32,
            )
            return 6

        h_cmd = pi.hProcess
        h_cmd_thread = pi.hThread

        # Job: create + KILL_ON_JOB_CLOSE + assign the SUSPENDED child.
        # Every step must succeed BEFORE ResumeThread; a partially-bound
        # child is terminated while still suspended and reported as an
        # explicit failure (never run an unbound admin command).
        job = _JobBinding()
        job_bound = job.setup(k32, h_cmd)
        if not job_bound:
            err_detail = job.failure_reason or "job binding failed"
            # Still-suspended child: terminate it (TerminateProcess on a
            # suspended thread is safe) and close handles.
            k32.TerminateProcess(h_cmd, 1)
            _write_message(
                h_control,
                {"kind": KIND_DONE, "v": PROTOCOL_VERSION, "nonce": nonce,
                 "rc": -1, "job_bound": False, "child_pid": None,
                 "error": f"job binding failed: {err_detail}"},
                k32,
            )
            k32.CloseHandle(h_cmd)
            k32.CloseHandle(h_cmd_thread)
            h_cmd = None
            h_cmd_thread = None
            job.close(k32)
            return 7

        # All three job steps succeeded: resume the suspended child.
        resume_rc = k32.ResumeThread(h_cmd_thread)
        if resume_rc == 0xFFFFFFFF:
            # ResumeThread failed (returns (DWORD)-1).  The child is still
            # suspended; terminate it so nothing unbounded ever runs.
            k32.TerminateProcess(h_cmd, 1)
            _write_message(
                h_control,
                {"kind": KIND_DONE, "v": PROTOCOL_VERSION, "nonce": nonce,
                 "rc": -1, "job_bound": True, "child_pid": None,
                 "error": "ResumeThread failed; suspended child terminated"},
                k32,
            )
            k32.CloseHandle(h_cmd)
            k32.CloseHandle(h_cmd_thread)
            h_cmd = None
            h_cmd_thread = None
            job.close(k32)
            return 8

        _write_message(
            h_control,
            {"kind": KIND_READY, "v": PROTOCOL_VERSION, "nonce": nonce,
             "job_bound": job.job_bound,
             "child_pid": int(pi.dwProcessId)},
            k32,
        )

        # --- cancel handling ---------------------------------------------
        cancel_seen = threading.Event()

        def _cancel_listener() -> None:
            try:
                while not cancel_seen.is_set():
                    avail = wintypes.DWORD()
                    k32.PeekNamedPipe(h_control, None, 0, None,
                                      ctypes.byref(avail), None)
                    if int(avail.value) > 0:
                        msg = _read_message(h_control, k32)
                        validate_parent_message(msg, nonce)
                        if msg.get("kind") == "cancel":
                            cancel_seen.set()
                            # Terminate the whole tree via the job when bound.
                            if job and job.job_bound:
                                job.terminate_tree(k32)
                            return
                    time.sleep(0.05)
            except Exception:
                cancel_seen.set()

        listener = threading.Thread(target=_cancel_listener, daemon=True)
        listener.start()

        wait = k32.WaitForSingleObject(h_cmd, INFINITE)
        code = wintypes.DWORD()
        k32.GetExitCodeProcess(h_cmd, ctypes.byref(code))

        if cancel_seen.is_set():
            terminated = job.job_bound if job else False
            _write_message(
                h_control,
                {"kind": KIND_CANCELLED, "v": PROTOCOL_VERSION, "nonce": nonce,
                 "rc": int(code.value), "terminated": terminated,
                 "job_bound": job.job_bound if job else False},
                k32,
            )
        else:
            _write_message(
                h_control,
                {"kind": KIND_DONE, "v": PROTOCOL_VERSION, "nonce": nonce,
                 "rc": int(code.value),
                 "job_bound": job.job_bound if job else False,
                 "child_pid": int(pi.dwProcessId)},
                k32,
            )
        return 0
    except Exception as exc:  # noqa: BLE001 - helper must fail closed
        try:
            if h_control:
                _write_message(
                    h_control,
                    {"kind": KIND_CANCELLED, "v": PROTOCOL_VERSION,
                     "nonce": nonce, "terminated": False,
                     "error": str(exc)[:400]},
                    k32,
                )
        except Exception:
            pass
        return 1
    finally:
        if h_cmd:
            k32.CloseHandle(h_cmd)
        if h_cmd_thread:
            k32.CloseHandle(h_cmd_thread)
        if job:
            job.close(k32)
        if attr_list:
            k32.DeleteProcThreadAttributeList(attr_list)
        if h_control:
            k32.CloseHandle(h_control)
        if h_output:
            k32.CloseHandle(h_output)


if __name__ == "__main__":
    sys.exit(main(sys.argv))
