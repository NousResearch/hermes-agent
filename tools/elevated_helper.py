def system_cmd_path() -> str:
    """Absolute path of the system cmd.exe (never PATH/COMSPEC/cwd)."""
    k32 = _kernel32()
    buf = ctypes.create_unicode_buffer(261)
    n = k32.GetSystemDirectoryW(buf, 261)
    if n == 0 or n >= 261:
        raise OSError("GetSystemDirectoryW failed")
    return os.path.join(buf.value, "cmd.exe")


def _build_env_block(env: dict) -> "ctypes.Array":
    """Build a Windows Unicode environment block from *env*.

    Windows requires the environment block to be sorted case-insensitively
    (CreateProcessW documents this; an unsorted block can mis-behave in
    child ``GetEnvironmentStrings`` enumeration).  Keys containing ``=``
    or a NUL, and values containing a NUL, are invalid on Windows and are
    rejected here (fail closed — never pass a malformed block to the
    elevated child).

    An EMPTY env still produces an explicit, non-None block containing a
    single NUL terminator pair.  Passing ``None`` to CreateProcessW would
    inherit the helper's ADMIN environment, which must never happen: the
    elevated child always receives exactly the scrubbed environment the
    parent approved.
    """
    from tools.elevated_protocol import ProtocolError

    for key, value in env.items():
        if not isinstance(key, str) or not isinstance(value, str):
            raise ProtocolError("env keys/values must be strings")
        if "=" in key:
            raise ProtocolError(f"env key contains '=': {key!r}")
        if "\x00" in key:
            raise ProtocolError("env key contains NUL")
        if "\x00" in value:
            raise ProtocolError(f"env value for {key!r} contains NUL")
    # Windows sorts environment blocks case-insensitively; mirror that so
    # the child sees a well-formed block (CreateProcessW documents the
    # requirement).
    items = sorted(env.items(), key=lambda kv: kv[0].casefold())
    parts = [f"{k}={v}" for k, v in items]
    # "\x00\x00" is the empty block terminator; create_unicode_buffer adds
    # its own trailing NUL, so "\x00" in Python yields "NUL NUL" on disk.
    joined = "\x00".join(parts) + "\x00" if parts else "\x00"
    return ctypes.create_unicode_buffer(joined)


def _read_message(h_pipe: int, k32) -> dict:
    """Read one framed control message from a message-mode pipe.

    Peek the pending message size, cap it, then read the whole message in a
    single ReadFile (message-mode pipes deliver one message per read).
    """
    total = wintypes.DWORD()
    avail = wintypes.DWORD()
    k32.PeekNamedPipe(h_pipe, None, 0, None, ctypes.byref(avail), ctypes.byref(total))
    size = int(total.value)
    if size == 0:
        raise ProtocolError("no message available")
    from tools.elevated_protocol import MAX_MESSAGE_BYTES

    if size > MAX_MESSAGE_BYTES:
        raise ProtocolError(f"message too large: {size}")
    buf = ctypes.create_string_buffer(size)
    nread = wintypes.DWORD()
    if not k32.ReadFile(h_pipe, buf, size, ctypes.byref(nread), None):
        raise ProtocolError(f"pipe read failed (error {ctypes.get_last_error()})")
    message, _consumed = unpack_frame(buf.raw[: int(nread.value)])
    return message


def _write_message(h_pipe: int, message: dict, k32) -> None:
    data = pack_message(message)
    nwritten = wintypes.DWORD()
    buf = ctypes.create_string_buffer(data)
    if not k32.WriteFile(h_pipe, buf, len(data), ctypes.byref(nwritten), None):
        raise OSError(f"pipe write failed (error {ctypes.get_last_error()})")


