"""Minimal trusted elevated launcher for terminal_tool's elevated path.

This helper is executed by the ADMIN process after ``ShellExecuteExW(..., "runas")``
elevates it.  It deliberately does almost nothing on its own, and every
privileged action is bound to the specific launch:

Security properties (round-7):

1. **No executable-search hijack.**  The shell is resolved via
   ``GetSystemDirectoryW`` and passed as the ABSOLUTE ``lpApplicationName``;
   a fake ``cmd.exe`` dropped in the working directory (or anywhere on PATH)
   can never be executed with administrator privileges.  ``PATH``,
   ``COMSPEC`` and the request environment are never trusted to locate the
   shell.

2. **No request TOCTOU.**  The command / cwd / sanitized env arrive over a
   framed named-pipe control protocol (``tools.elevated_protocol.py``) whose
   nonce was generated by the parent before launch and whose client PID was
   verified against the elevated process handle.  A user-writable
   ``request.json`` is no longer read, so nothing can be tampered with after
   the guard approved the command.

3. **No arbitrary file writes.**  The helper never creates, overwrites or
   truncates files for medium-integrity-controlled paths.  stdout/stderr
   stream back to the parent over a separate output named pipe; the exit
   code and status travel on the control pipe.

4. **Job object truthfulness.**  Job creation / ``KILL_ON_JOB_CLOSE`` /
   child assignment are checked step by step; ``job_bound`` is only reported
   when ALL of them succeeded.  Timeout termination claims a terminated tree
   only after the job was terminated and the child verified dead.

5. **Handle allowlist.**  The elevated child is created with
   ``STARTUPINFOEXW`` + ``PROC_THREAD_ATTRIBUTE_HANDLE_LIST`` containing ONLY
   the stdout/stderr handles; sockets, tokens, files, pipes and the job
   handle are never inherited.
"""

