class _JobBinding:
    """Tracks whether the job was created, configured AND assigned.

    ``job_bound`` is only True when all three steps succeeded, so the parent
    never claims a terminated tree on the strength of a half-configured job.
    Each step records a human-readable failure reason for the error message
    when the binding is incomplete.
    """

    def __init__(self) -> None:
        self.handle = None
        self.created = False
        self.limit_set = False
        self.assigned = False
        self.failure_reason: "str | None" = None

    @property
    def job_bound(self) -> bool:
        return self.created and self.limit_set and self.assigned

    def setup(self, k32, child_process: int) -> bool:
        """Create the job, set KILL_ON_JOB_CLOSE, assign the SUSPENDED child.

        Returns True only when ALL three steps succeeded.  On failure the
        partial state remains visible via ``job_bound`` / ``failure_reason``
        so the caller can terminate the still-suspended child and report an
        explicit error.
        """
        job = k32.CreateJobObjectW(None, None)
        if not job:
            self.failure_reason = (
                f"CreateJobObjectW failed (error {ctypes.get_last_error()})"
            )
            return False
        self.handle = job
        self.created = True
        info = _JOBOBJECT_EXTENDED_LIMIT_INFORMATION()
        info.BasicLimitInformation.LimitFlags = JOB_OBJECT_LIMIT_KILL_ON_JOB_CLOSE
        if not k32.SetInformationJobObject(
            job,
            JobObjectExtendedLimitInformation,
            ctypes.byref(info),
            ctypes.sizeof(info),
        ):
            self.failure_reason = (
                f"SetInformationJobObject failed (error {ctypes.get_last_error()})"
            )
            return False
        self.limit_set = True
        if not k32.AssignProcessToJobObject(job, child_process):
            self.failure_reason = (
                f"AssignProcessToJobObject failed (error {ctypes.get_last_error()})"
            )
            return False
        self.assigned = True
        return True

    def terminate_tree(self, k32, exit_code: int = 1) -> bool:
        if self.handle and self.created:
            return bool(k32.TerminateJobObject(self.handle, exit_code))
        return False

    def close(self, k32) -> None:
        if self.handle:
            k32.CloseHandle(self.handle)
            self.handle = None


