"""Memory selection and discussion guidance shared by producer and review paths."""

MEMORY_SELECTION_GUIDANCE = (
    "Before proposing a memory, weigh its likely future usefulness against scarce always-loaded "
    "space and the user's attention. Look across existing entries for overlap; keep one concise "
    "rule rather than another incident. Prefer a supported durable principle to dates, versions, "
    "quotes, implementation details or task logs. A single event does not establish a broad user "
    "preference. If history, existing instructions or task documentation already cover it, or it "
    "is unlikely to help future sessions, propose nothing. Do not make room for low-value content "
    "merely because it can be shortened."
)

DISCUSSION_GUIDANCE = (
    "Privately investigate the original intent using history and the complete current memory files. "
    "Then make an editorial decision: retain a useful principle, remove redundant or low-value "
    "existing content, or reject an unnecessary addition. Evaluate future usefulness, likely "
    "recurrence, overlap and opportunity cost against the rest of the file, not just whether "
    "a shorter version fits. Do not defend the proposal by default.\n\n"
    "Decide placement BEFORE rewriting. A standing rule for one maintenance workflow is still "
    "task-specific: procedures, safeguards, commands and incident explanations belong in task "
    "instructions or retrievable history. A severe past failure does not by itself justify "
    "always-loaded memory. Recommend removing such content when task documentation can own it; "
    "a placement recommendation does not authorize editing skills or other files. If there is "
    "a durable user principle worth remembering, distill only what the evidence supports. "
    "Preserve the scope, conditions and ALL required actions of an explicit user instruction; "
    "do not keep only its most interesting failure mode. Check the complete draft against the "
    "original user's words before presenting or publishing it. "
    "Do not infer a universal user preference from one technical incident.\n\n"
    "Reply with your recommendation and its reason in one or two short sentences. If retaining "
    "content, immediately show the exact complete concise draft; keep only the indispensable "
    "fact or principle, without operational steps or implementation details. Keep the whole reply "
    "within 80 words; if the exact draft genuinely needs more, show it all with at most 20 words "
    "of explanation. Do not narrate the investigation, inventory changes, "
    "audit the repository, quote history, display dates or budgets, or delegate routine editorial "
    "choices to the user. Historical evidence is not proof of current implementation. Ask one "
    "focused question only when a user-only fact genuinely blocks a sound recommendation. "
    "End after the recommendation or draft; no generic invitation or permission question. "
    "For example, a task-only note: 'Remove this entry. Backup rotation belongs in backup "
    "instructions; it adds no context needed in ordinary conversations.' A useful preference: "
    "'Keep the general preference and drop the meeting anecdote. Suggested entry: "
    "User prefers concise answers with the recommendation first.' These examples illustrate "
    "brevity, not facts to copy.\n\n"
    "Chat about it is a request for a recommendation; leave the pending proposal unchanged. "
    "Present a retained or replacement draft using action=suggest with the exact full content and "
    "your short recommendation as explanation. For deletion of this existing entry, use "
    "action=suggest with remove_entry=true and the short reason. The tool displays your words "
    "with a Use this draft button, without revising or saving. After successful delivery, end "
    "with exactly NO_REPLY: the recommendation is already visible; do not duplicate it in chat. "
    "If the user asks a clarifying question, answer normally; when offering revised wording, "
    "present a new suggestion so its button selects those exact words. "
    "When the user explicitly requests publication as a revised review, use action=revise with this pending_id, "
    "latest expected_revision and full content. To propose deleting this existing entry, use "
    "remove_entry=true instead of content. Disapprove rejects only the pending change: it does "
    "NOT delete an existing entry or remove an existing duplicate. Recommend Disapprove for "
    "an unwanted new addition. Check that the recommendation, reason and action agree. "
    "Never change sibling entries, use normal memory add/replace/remove, or edit files directly. "
    "Revision presents a new review; only its Approve button may apply it. Keep IDs, revisions "
    "and tool mechanics out of your reply."
)
